export default async function tree(t) {
  const { page } = t
  const visible = () => page.locator("#tree [role=treeitem]:visible").evaluateAll((els) => els.map((el) => el.id).join(","))
  t.eq("a tree of items, one tab stop", [await t.attr("#tree", "role"), await t.count('#tree [tabindex="0"]'), await t.attr("#t-europe", "tabindex")].join(" "), "tree 1 0")
  t.eq("items with a group are branches, read from the markup", [await t.attr("#t-europe", "aria-expanded"), await t.attr("#t-italy", "aria-expanded"), await t.attr("#t-asia", "aria-expanded"), await t.attr("#t-oceania", "aria-expanded")].join(" "), "true false false ")
  t.eq("levels and positions", [await t.attr("#t-france", "aria-level"), await t.attr("#t-france", "aria-posinset"), await t.attr("#t-france", "aria-setsize")].join(" "), "2 1 3")
  t.eq("a collapsed branch's group is not rendered", await visible(), "t-europe,t-france,t-spain,t-italy,t-asia,t-oceania")
  await page.locator("#t-europe").focus()
  await t.press("ArrowDown")
  t.eq("ArrowDown moves to the next visible item", await t.active(), "t-france")
  await t.press("ArrowDown")
  await t.press("ArrowDown")
  t.eq("disabled items stay focusable", await t.active(), "t-italy")
  await t.press("ArrowRight")
  t.eq("ArrowRight expands a branch", (await t.attr("#t-italy", "aria-expanded")) + " " + (await t.active()), "true t-italy")
  await t.press("ArrowRight")
  t.eq("ArrowRight again moves into it", await t.active(), "t-rome")
  await t.press("ArrowLeft")
  t.eq("ArrowLeft moves to the parent", await t.active(), "t-italy")
  await t.press("ArrowLeft")
  t.eq("ArrowLeft collapses an open branch", (await t.attr("#t-italy", "aria-expanded")) + " " + (await t.count("#t-rome")), "false 0")
  await t.press("End")
  t.eq("End moves to the last visible item", await t.active(), "t-oceania")
  await t.press("Home")
  t.eq("Home moves to the first item", await t.active(), "t-europe")
  await t.press("j")
  t.eq("typeahead skips items in collapsed branches", await t.active(), "t-europe")
  await t.settle(600)
  await t.press("a")
  t.eq("typeahead moves to a matching item", await t.active(), "t-asia")
  await t.press("*")
  t.eq("* expands every sibling branch", (await t.attr("#t-asia", "aria-expanded")) + " " + (await t.count("#t-japan")), "true 1")
  await t.press("Enter")
  t.eq("Enter selects the focused item", await t.attr("#t-asia", "aria-selected"), "true")
  await page.click("#t-france")
  t.eq("a click selects one item", (await t.attr("#t-france", "aria-selected")) + " " + (await t.attr("#t-asia", "aria-selected")), "true false")
  await page.click("#t-europe-ind")
  t.eq("the indicator collapses its branch", (await t.attr("#t-europe", "aria-expanded")) + " " + (await t.count("#t-france")), "false 0")
  await t.press("Tab")
  t.eq("Tab leaves the tree", await t.active(), "tree-after")
  await t.press("Shift+Tab")
  t.eq("Shift+Tab returns to its tab stop", await t.active(), "t-europe")

  const ditems = "#dtree [role=treeitem]"
  t.eq("data: items render from data, a link label for an href", [await t.count(ditems), await page.locator("#dtree a[data-slot=tree-label]").getAttribute("href")].join(" "), "3 #readme")
  await page.locator(ditems).first().focus()
  await t.press("ArrowRight")
  t.eq("data: expanding a branch renders its children", await t.count(ditems), 5)
  await page.locator(ditems).nth(1).focus()
  await t.press("Space")
  t.eq("checkable: Space checks an item and its branch reads mixed", (await t.text("#dtree-checked")) + " " + (await page.locator(ditems).first().getAttribute("aria-checked")), "src/index.ts mixed")
  await page.locator(ditems).first().focus()
  await t.press("Space")
  t.eq("checking a branch checks its children", (await t.text("#dtree-checked")) + " " + (await page.locator(ditems).nth(2).getAttribute("aria-checked")), "src/index.ts,src/util.ts true")
  await page.click("#dtree-more")
  await t.settle()
  t.eq("data: a changed list adds its items", (await t.count(ditems)) + " " + (await page.locator(ditems).last().textContent()), "6 LICENSE")

  const mitems = "#mtree [role=treeitem]"
  t.eq("multiple: multiselectable, from paths", (await t.attr("#mtree", "aria-multiselectable")) + " " + (await t.count(mitems)), "true 2")
  await page.locator(mitems).first().click()
  await page.locator(mitems).last().click({ modifiers: ["Control"] })
  t.eq("multiple: Control+click adds to the selection", await t.text("#mtree-value"), "a,b")
}
