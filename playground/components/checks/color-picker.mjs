export default async function colorPickerChecks(t) {
  t.eq("a named group", (await t.attr("#cp", "role")) + " " + (await t.attr("#cp", "aria-label")), "group Brand color")
  t.eq("the text input starts at the value", await t.page.inputValue("#cp-input"), "#ff0000")
  t.eq("the area thumb is a slider for both channels", (await t.attr("#cp-area-thumb", "role")) + " " + (await t.attr("#cp-area-thumb", "aria-label")), "slider Saturation and brightness")
  t.eq("the hue slider says its value", (await t.attr("#cp-hue [role=slider]", "aria-label")) + " " + (await t.attr("#cp-hue [role=slider]", "aria-valuenow")), "Hue 0")
  t.eq("the swatch is an image named by its color", (await t.attr("#cp-swatch", "role")) + " " + Boolean(await t.attr("#cp-swatch", "aria-label")), "img true")
  t.eq("a channel input shows its channel, named by it", (await t.page.inputValue("#cp-sat")) + " " + (await t.attr("#cp-sat", "aria-label")), "100 Saturation")
  await t.page.focus("#cp-hue [role=slider]")
  await t.press("ArrowRight")
  t.check("ArrowRight on the hue slider changes the color", (await t.page.inputValue("#cp-input")) !== "#ff0000", await t.page.inputValue("#cp-input"))
  await t.page.fill("#cp-input", "rebeccapurple")
  await t.press("Enter")
  t.eq("the text input reads a CSS color on Enter", await t.page.inputValue("#cp-input"), "#663399")
  await t.page.fill("#cp-input", "not a color")
  await t.press("Tab")
  t.eq("text that isn't a color goes back", await t.page.inputValue("#cp-input"), "#663399")
  t.eq("presets are a listbox of options", (await t.attr("#cp-presets", "role")) + " " + (await t.attrs("#cp-presets [role=option]", "aria-selected")), "listbox false,false")
  await t.page.locator("#cp-presets [role=option]").first().click()
  t.eq("pressing a preset sets the value", (await t.page.inputValue("#cp-input")) + " " + (await t.attr("#cp-presets [role=option]", "aria-selected")), "#00ff00 true")
  t.check("the eye dropper is a button, disabled where unsupported", (await t.attr("#cp-dropper", "data-unsupported")) === null || (await t.attr("#cp-dropper", "disabled")) !== null, "")
  await t.page.click("#cp-form-submit")
  t.eq("the hidden input submits the color", await t.text("#cp-form-sent"), "brand=#00ff00")

  await t.page.fill("#ccp-input", "#123456")
  await t.press("Enter")
  t.eq("controlled: a typed color reaches the app", await t.text("#ccp-value"), "#123456")
  await t.page.click("#ccp-outside")
  t.eq("controlled: a value from outside shows", await t.page.inputValue("#ccp-input"), "#000000")

  t.eq("in a field: named by its label, with the field's name", (await t.attr("#fcp", "aria-labelledby")) + " " + (await t.page.locator("#fcp input").first().getAttribute("name")), "fcp-label tint")
}
