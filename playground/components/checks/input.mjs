export default async function inputChecks(t) {
  t.eq("uncontrolled: a native input with its default value", await t.page.inputValue("#in"), "hello")
  t.eq("filled says so", await t.attr("#in", "data-filled"), "")
  await t.page.fill("#in", "")
  t.eq("emptied: no longer filled", await t.attr("#in", "data-filled"), null)
  await t.page.type("#in", "octane")
  await t.page.click("#in-form-submit")
  t.eq("it submits what was typed under its name", await t.text("#in-form-sent"), "q=octane")
  await t.page.click("#in-form-reset")
  await t.settle()
  t.eq("a form reset returns its default", (await t.page.inputValue("#in")) + " " + (await t.attr("#in", "data-filled")), "hello ")

  await t.page.click("#cin")
  await t.page.keyboard.press("End")
  await t.page.keyboard.type("c")
  await t.settle()
  t.eq("controlled: typing reaches the app, and the app's value shows", (await t.page.inputValue("#cin")) + " " + (await t.text("#cin-value")), "ABC ABC")
  t.eq("controlled: the change says it came from typing", await t.text("#cin-reasons"), "input-change")
  await t.page.click("#cin-outside")
  t.eq("controlled: a value from outside shows", await t.page.inputValue("#cin"), "SET")

  await t.page.click("#fin")
  await t.page.keyboard.type("x")
  await t.settle()
  t.eq("controlled with no handler: typing is refused", await t.page.inputValue("#fin"), "fixed")

  t.eq("in a field: named, described, required", (await t.attr("#field-in", "aria-labelledby")) + " " + (await t.attr("#field-in", "aria-describedby")) + " " + (await t.attr("#field-in", "required")), "fin-label fin-description ")
  t.eq("in a field: takes the field's name", await t.attr("#field-in", "name"), "email")
  await t.page.click("#fin-label")
  t.eq("in a field: its label focuses it", await t.active(), "field-in")
  t.eq("in a disabled field: disabled", (await t.attr("#field-off", "disabled")) + " " + (await t.attr("#field-off", "data-disabled")), " ")

  t.eq("group: says its field is filled; clear shows", (await t.attr("#grp", "data-filled")) + " " + (await t.visible("#grp-clear")), " true")
  await t.page.click("#grp-icon")
  t.eq("group: a press on its icon focuses the field", await t.active(), "grp-in")
  await t.page.click("#grp-clear")
  t.eq("group: clear empties the field and focuses it", (await t.page.inputValue("#grp-in")) + "|" + (await t.active()), "|grp-in")
  t.eq("group: no longer filled, clear hides", (await t.attr("#grp", "data-filled")) + " " + (await t.visible("#grp-clear")), "null false")
}
