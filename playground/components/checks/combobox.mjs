export default async function combobox(t) {
  const { page } = t
  const shown = (list) => page.locator(list + " [role=option]:visible").allTextContents().then((all) => all.join(","))
  t.eq("the input is a combobox named by its label, holding the value's label", [await t.attr("#c-input", "role"), await t.attr("#c-input", "aria-labelledby"), await t.attr("#c-input", "aria-expanded"), await page.inputValue("#c-input")].join(" "), "combobox c-label false Banana")
  t.eq("the trigger is out of the tab order", await t.attr("#c-trigger", "tabindex"), "-1")
  await page.click("#c-label")
  t.eq("the label focuses the input", await t.active(), "c-input")
  await t.press("ArrowDown")
  t.eq("ArrowDown opens the list highlighting the first item, focus staying in the input", [await t.visible("#c-content"), await t.attr("#c-input", "aria-expanded"), await t.attr("#c-input", "aria-activedescendant"), await t.active()].join(" "), "true true c-Apple c-input")
  await t.press("ArrowDown")
  t.eq("ArrowDown moves the highlight past a disabled item", await t.attr("#c-input", "aria-activedescendant"), "c-Banana")
  await t.press("ArrowUp")
  await t.press("ArrowUp")
  t.eq("ArrowUp from the first item wraps to the last", await t.attr("#c-input", "aria-activedescendant"), "c-Mango")
  await t.press("Escape")
  t.eq("Escape closes the list and keeps the text", (await t.visible("#c-content")) + " " + (await page.inputValue("#c-input")), "false Banana")
  await page.fill("#c-input", "")
  await page.keyboard.type("ap")
  await t.settle()
  t.eq("typing opens and filters the list", (await t.visible("#c-content")) + " " + (await shown("#c-list")), "true Apple,Apricot,Grape")
  t.eq("the matched text is marked", await page.locator("#c-Apple mark").first().textContent(), "Ap")
  t.eq("nothing is highlighted while typing", await t.attr("#c-input", "aria-activedescendant"), null)
  await t.press("ArrowDown")
  await t.press("ArrowDown")
  t.eq("arrows move through the matches, skipping a disabled one", await t.attr("#c-input", "aria-activedescendant"), "c-Grape")
  await t.press("Enter")
  t.eq("Enter selects, fills the input and closes", (await page.inputValue("#c-input")) + " " + (await t.visible("#c-content")), "Grape false")
  await page.fill("#c-input", "zz")
  await t.settle()
  t.eq("no match shows the empty part", (await shown("#c-list")) + "|" + (await t.text("#c-empty")), "|No fruit")
  await page.click("#c-after")
  await t.settle()
  t.eq("leaving closes it and restores the value's label", (await t.visible("#c-content")) + " " + (await page.inputValue("#c-input")), "false Grape")
  await page.click("#c-trigger")
  t.eq("the trigger opens the whole list, focus in the input", (await t.visible("#c-content")) + " " + (await shown("#c-list")).split(",").length + " " + (await t.active()), "true 8 c-input")
  await page.click("#c-Cherry")
  t.eq("a click selects and closes", (await page.inputValue("#c-input")) + " " + (await t.visible("#c-content")), "Cherry false")
  await page.click("#c-form-submit")
  t.eq("it submits its value under its name", await t.text("#c-form-sent"), "fruit=Cherry")
  await page.click("#c-clear")
  t.eq("clear empties the input and the value", (await page.inputValue("#c-input")) + "|" + (await t.attrs("#c-list [role=option]", "aria-selected")).includes("true"), "|false")
  await page.click("#c-form-reset")
  await t.settle()
  t.eq("a form reset restores the default", await page.inputValue("#c-input"), "Banana")

  t.eq("chips: one per value, in a toolbar", (await t.attr("#m-chips", "role")) + " " + (await t.count("[data-slot=combobox-chip]")), "toolbar 1")
  await page.click("#m-input")
  await page.keyboard.type("m")
  await t.settle()
  const mlist = "#" + (await t.attr("#m-input", "aria-controls")).replaceAll(":", "\\:")
  t.eq("multiple: data items filter as you type", await shown(mlist), "Lemon,Mango")
  await t.press("ArrowDown")
  await t.press("ArrowDown")
  await t.press("Enter")
  t.eq("multiple: Enter adds the value, a chip appears and the text clears", [await t.text("#m-value"), await t.count("[data-slot=combobox-chip]"), await page.inputValue("#m-input")].join(" "), "Lemon,Mango 2 ")
  await page.click("#m-remove-Lemon")
  t.eq("a chip's remove button removes its value", (await t.text("#m-value")) + " " + (await t.count("#m-chip-Lemon")), "Mango 0")
  await page.focus("#m-input")
  await t.press("Backspace")
  t.eq("Backspace in an empty input removes the last value", await t.text("#m-value"), "")
  await t.press("Escape")
  await page.click("#m-set")
  t.eq("controlled: a value set from outside makes chips", await t.attrs("[data-slot=combobox-chip]", "data-value"), "Apple,Mango")
  await page.click("#m-form-submit")
  t.eq("multiple: every value submits", await t.text("#m-form-sent"), "tag=Apple&tag=Mango")

  await page.click("#n-input")
  await page.keyboard.type("Blue")
  await t.settle()
  t.eq("create: offered for text matching no item", await t.text("#n-create"), "Create “Blue”")
  await t.press("ArrowDown")
  await t.press("Enter")
  await t.settle()
  t.eq("create: choosing it adds and selects the item", (await t.text("#n-value")) + " " + (await page.inputValue("#n-input")), "Blue Blue")

  await page.click("#a-input")
  await page.keyboard.type("ar")
  await t.settle(300)
  t.eq("async: the loaded items show, with a status", (await shown("#a-content")) + " " + (await t.text("#a-status")), "Barbara Liskov,Margaret Hamilton 2 results")
  await page.keyboard.type("g")
  await t.settle(300)
  t.eq("async: a longer query loads again", await shown("#a-content"), "Margaret Hamilton")
  await t.press("ArrowDown")
  await t.press("Enter")
  t.eq("async: Enter selects a loaded item", await t.text("#a-value"), "Margaret Hamilton")

  t.eq("in a field: the field's label names the input, its name submits", (await t.attr("#f-input", "aria-labelledby")) + " " + (await t.attr("#page-combobox [data-slot=field] textarea", "name")), "f-label city")
}
