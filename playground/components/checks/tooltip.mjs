export default async function tooltip(t) {
  const { page } = t
  const shown = (selector) => page.locator(selector).evaluate((el) => !el.hidden && el.matches(":popover-open")).catch(() => false)
  t.eq("closed at first", await shown("#tip"), false)
  await page.hover("#tip-trigger")
  await t.settle(30)
  t.eq("waits for its delay", await shown("#tip"), false)
  await t.settle(250)
  t.eq("resting the pointer on the trigger opens it", await shown("#tip"), true)
  t.eq("a tooltip that describes its trigger", [await t.attr("#tip", "role"), await t.attr("#tip-trigger", "aria-describedby")].join(" "), "tooltip tip")
  t.eq("opening on hover leaves focus where it was", await t.active(), "body")
  const above = await page.evaluate(() => Math.round(document.getElementById("tip-trigger").getBoundingClientRect().top - document.getElementById("tip").getBoundingClientRect().bottom))
  t.eq("opens above the trigger, by the side offset", above, 4)
  t.eq("shows the shortcut, and the trigger says it", (await t.text("#tip-shortcut")).includes("S") && (await t.attr("#tip-trigger", "aria-keyshortcuts")) !== null, true)
  await page.hover("#tip")
  await t.settle(200)
  t.eq("the pointer can move onto the tooltip", await shown("#tip"), true)
  await page.mouse.move(600, 500)
  await t.settle(400)
  t.eq("moving the pointer away closes it", await shown("#tip"), false)

  await page.locator("#tip-before").focus()
  await t.press("Tab")
  await t.settle(150)
  t.eq("keyboard focus on the trigger opens it", await shown("#tip"), true)
  await t.press("Escape")
  t.eq("Escape closes it and leaves focus on the trigger", (await shown("#tip")) + " " + (await t.active()), "false tip-trigger")
  await t.press("Tab")
  await t.settle(150)
  t.eq("Tab shows the next tooltip, below its trigger", (await shown("#tip2")) + " " + (await t.attr("#tip2", "data-side")), "true bottom")
  t.eq("only one tooltip is open at a time", await shown("#tip"), false)
  await t.press("Tab")
  await t.settle(150)
  t.eq("focus leaving the trigger closes it", await shown("#tip2"), false)

  await page.hover("#tip2-trigger")
  await t.settle(300)
  await page.click("#tip2-trigger")
  await t.settle(100)
  t.eq("pressing the trigger closes the tooltip", await shown("#tip2"), false)

  await page.click("#rtip-api")
  await t.settle(100)
  t.eq("a controller opens it without moving focus", (await shown("#rtip")) + " " + (await t.active()), "true rtip-api")
  t.eq("the outside trigger is described by it", await t.attr("#rtip-trigger", "aria-describedby"), "rtip")
  await page.mouse.move(600, 500)

  await page.hover("#dtip-trigger")
  await t.settle(900)
  t.eq("a disabled tooltip never opens", await shown("#dtip"), false)
}
