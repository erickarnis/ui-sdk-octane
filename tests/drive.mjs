import { chromium } from "playwright"
const browser = await chromium.launch()
const page = await browser.newPage()
const problems = []
page.on("console", (m) => { if (["error", "warning"].includes(m.type())) problems.push(m.type() + ": " + m.text()) })
page.on("pageerror", (e) => problems.push("pageerror: " + e.message + "\n" + (e.stack ?? "").split("\n").slice(0, 6).join("\n")))
await page.goto(process.argv[2] ?? "http://127.0.0.1:4399/")
await page.waitForTimeout(800)
const results = []
const check = (name, ok, detail = "") => results.push(`${ok ? "ok  " : "FAIL"} ${name}${detail ? " — " + detail : ""}`)
const attr = (sel, name) => page.locator(sel).getAttribute(name)
const html = async (sel) => (await page.locator(sel).evaluate((el) => el.outerHTML)).slice(0, 400)
try {
  // 1. uncontrolled toggle
  check("mute renders button with type and aria-pressed", (await attr("#mute", "aria-pressed")) === "false" && (await attr("#mute", "type")) === "button")
  check("mute keeps app className", (await attr("#mute", "class")) === "plain", String(await attr("#mute", "class")))
  await page.click("#mute")
  check("mute toggles on click", (await attr("#mute", "aria-pressed")) === "true")
  await page.focus("#mute"); await page.keyboard.press("Space")
  check("mute toggles on Space", (await attr("#mute", "aria-pressed")) === "false")
  // 2. controlled toggle
  await page.click("#cmute")
  check("controlled: press reaches the app and comes back", (await attr("#cmute", "aria-pressed")) === "true" && (await page.textContent("#cmute")) === "Unmute")
  check("controlled: app onClick ran too", (await page.textContent("#log")) === "app-click", String(await page.textContent("#log")))
  await page.click("#outside")
  check("controlled: outside change shows", (await attr("#cmute", "aria-pressed")) === "false")
  await page.click("#lock"); await page.click("#cmute")
  check("controlled: refused change stays", (await attr("#cmute", "aria-pressed")) === "false")
  await page.click("#lock")
  // 3. hand-written part with a class function of state
  await page.click("#hmute")
  check("hand part: toggles and keeps class", (await attr("#hmute", "aria-pressed")) === "true" && ((await attr("#hmute", "class")) ?? "").startsWith("hand"), String(await attr("#hmute", "class")))
  // mount, unmount, mount again
  await page.click("#mounted")
  check("mounted part toggles", (await attr("#mounted", "aria-pressed")) === "true")
  await page.click("#toggle-mount")
  check("part leaves the page", (await page.locator("#mounted").count()) === 0)
  await page.waitForTimeout(50)
  await page.click("#toggle-mount")
  check("part returns with fresh state", (await attr("#mounted", "aria-pressed")) === "false")
  await page.click("#mounted")
  check("returned part works", (await attr("#mounted", "aria-pressed")) === "true")
  // 4. rating: roving focus
  const tabindexes = async () => page.locator("#stars [role=radio]").evaluateAll((els) => els.map((el) => el.getAttribute("tabindex")).join(","))
  check("rating: one tab stop on the chosen star", (await tabindexes()) === "-1,0,-1,-1,-1", await tabindexes())
  await page.locator("#stars [role=radio]").nth(1).focus()
  await page.keyboard.press("ArrowRight")
  check("rating: ArrowRight moves and rates", (await page.textContent("#stars-value")) === "3" && (await page.evaluate(() => document.activeElement?.getAttribute("aria-label"))) === "3 stars", await page.textContent("#stars-value") + " / " + await page.evaluate(() => document.activeElement?.getAttribute("aria-label")))
  check("rating: tab stop followed", (await tabindexes()) === "-1,-1,0,-1,-1", await tabindexes())
  await page.keyboard.press("ArrowLeft"); await page.keyboard.press("ArrowLeft"); await page.keyboard.press("ArrowLeft")
  check("rating: loops past the first star", (await page.textContent("#stars-value")) === "5", String(await page.textContent("#stars-value")))
  await page.locator("#stars [role=radio]").nth(0).click()
  check("rating: click rates", (await page.textContent("#stars-value")) === "1")
  check("rating: data-filled follows", (await page.locator("#stars [data-filled]").count()) === 1)
  // 5. tabs from @ui-sdk/core/tabs
  const selected = async () => page.locator("#tabs [role=tab]").evaluateAll((els) => els.map((el) => el.getAttribute("aria-selected")).join(","))
  const panels = async () => page.locator("#tabs [role=tabpanel]").evaluateAll((els) => els.filter((el) => !el.hidden).map((el) => el.textContent).join("|"))
  check("tabs: first selected, one panel", (await selected()) === "true,false,false" && (await panels()) === "Panel A", (await selected()) + " / " + (await panels()))
  const beta = page.locator("#tabs [role=tab]").nth(1)
  check("tabs: state functions before", (await beta.getAttribute("class")) === "off" && (await beta.textContent()) === "Beta", (await beta.getAttribute("class")) + " / " + (await beta.textContent()))
  await page.locator("#tabs [role=tab]").nth(1).click()
  check("tabs: state functions after", (await beta.getAttribute("class")) === "on" && (await beta.textContent()) === "Beta (open)", (await beta.getAttribute("class")) + " / " + (await beta.textContent()))
  check("tabs: click selects", (await selected()) === "false,true,false" && (await panels()) === "Panel B", (await selected()) + " / " + (await panels()))
  await page.keyboard.press("ArrowRight")
  check("tabs: arrow moves to render-prop tab", (await selected()) === "false,false,true" && (await panels()) === "Panel C", (await selected()) + " / " + (await panels()))
  const third = page.locator("#tabs [role=tab]").nth(2)
  check("tabs: render element kept its tag and props", (await third.evaluate((el) => el.tagName + ":" + el.getAttribute("data-custom"))) === "A:yes", await third.evaluate((el) => el.tagName + ":" + el.getAttribute("data-custom")))
  const controls = await third.getAttribute("aria-controls")
  check("tabs: aria-controls points at the shown panel", !!controls && (await page.locator(`[id="${controls}"]`).textContent()) === "Panel C", String(controls))
} catch (error) {
  results.push("THREW " + error.message.split("\n")[0])
}
console.log(results.join("\n"))
console.log(problems.length ? "PROBLEMS\n" + problems.join("\n") : "no console problems")
await browser.close()
