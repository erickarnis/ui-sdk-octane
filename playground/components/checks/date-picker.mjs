export default async function datePicker(t) {
  const { page } = t
  const content = "#dp [data-slot=date-picker-content]"
  const trigger = "#dp [data-slot=date-picker-trigger]"
  const input = "#dp [data-slot=date-picker-input]"
  const hidden = (root, n = 0) => page.locator(`#${root} input[type=hidden]`).nth(n).inputValue()
  const focused = () => page.evaluate(() => document.activeElement?.getAttribute("data-value") ?? document.activeElement?.getAttribute("data-slot"))
  t.eq("an input named by the field, and a trigger that opens a dialog", [await t.attr(input, "aria-labelledby"), await t.attr(trigger, "aria-haspopup"), await t.attr(trigger, "aria-expanded"), await t.count(content)].join(" "), "dp-label dialog false 0")
  await page.click(trigger)
  t.eq("the trigger opens the calendar in the top layer", [await t.attr(content, "role"), await page.locator(content).evaluate((el) => el.matches(":popover-open")), await t.text(`${content} [data-slot=calendar-heading]`)].join(" "), "dialog true March 2026")
  t.eq("focus moves to today's day", await focused(), "2026-03-10")
  t.eq("days before min are disabled", await t.attr(`${content} [data-value="2026-03-04"]`, "aria-disabled"), "true")
  await t.press("ArrowRight")
  await t.press("ArrowDown")
  t.eq("arrow keys move in the grid", await focused(), "2026-03-18")
  await t.press("Enter")
  await t.settle()
  t.eq("Enter picks the day, closes the calendar and returns focus to the trigger", [await t.count(content), await focused()].join(" "), "0 date-picker-trigger")
  t.eq("the input shows the date in the locale, the hidden input holds it in ISO", [await page.locator(input).inputValue(), await hidden("dp")].join(" "), "03/18/2026 2026-03-18")
  await page.click("#dp-form-submit")
  t.eq("it submits with the form under the field's name", await t.text("#dp-form-sent"), "due=2026-03-18")
  await page.fill(input, "4/2/2026")
  await page.locator(input).press("Enter")
  t.eq("a date typed in the input, which is also the field's control, is read on Enter", [await page.locator(input).inputValue(), await hidden("dp")].join(" "), "04/02/2026 2026-04-02")
  await page.click(trigger)
  t.eq("the calendar opens at the chosen date", [await t.text(`${content} [data-slot=calendar-heading]`), await focused()].join(" "), "April 2026 2026-04-02")
  await t.press("Escape")
  await t.settle()
  t.eq("Escape closes it and returns focus to the trigger", [await t.count(content), await focused()].join(" "), "0 date-picker-trigger")
  await page.click(trigger)
  await page.click("#dp-label", { position: { x: 2, y: 2 } })
  await t.settle()
  t.eq("an outside press closes it", await t.count(content), 0)
  await page.fill(input, "3/1/2026")
  await page.locator(input).press("Enter")
  t.eq("a typed date before min is marked invalid and not taken", [await t.attr(input, "aria-invalid"), await hidden("dp")].join(" "), "true 2026-04-02")

  await page.click("#rdp-trigger")
  t.eq("controlled: the trigger asks the app to open", [await t.text("#rdp-open"), await t.count("#rdp-content")].join(" "), "true 1")
  t.eq("two months in range mode", await t.count("#rdp-content table"), 2)
  await page.click('#rdp-content [data-value="2026-06-10"]')
  await page.click('#rdp-content [data-value="2026-07-02"]')
  await t.settle()
  t.eq("a range picked in the calendar reaches the app", await t.text("#rdp-value"), '["2026-06-10","2026-07-02"]')
  t.eq("the inputs show its ends", [await page.locator("#rdp-start").inputValue(), await page.locator("#rdp-end").inputValue()].join(" "), "06/10/2026 07/02/2026")
  t.eq("the hint gives the format and describes the inputs", [await t.text("#rdp-hint"), (await t.attr("#rdp-start", "aria-describedby")) === "rdp-hint"].join(" "), "MM/DD/YYYY true")
  if ((await t.count("#rdp-content")) === 0) await page.click("#rdp-trigger")
  await page.click("#rdp-week")
  await t.settle()
  t.eq("a preset selects its value", await t.text("#rdp-value"), '["2026-06-01","2026-06-07"]')
  await page.click("#rdp-clear")
  t.eq("Clear empties the value and focuses the input", [await t.text("#rdp-value"), await t.active()].join(" "), "null rdp-start")
}
