export default async function scrollAreaChecks(t) {
  const top = () => t.page.locator("#sa-viewport").evaluate((el) => el.scrollTop)
  t.eq("the viewport is the native scroller, its own scrollbars hidden", await t.page.locator("#sa-viewport").evaluate((el) => getComputedStyle(el).overflow + " " + getComputedStyle(el).scrollbarWidth), "auto none")
  t.eq("it overflows both ways, at the start", (await t.attr("#sa", "data-overflow-y")) + " " + (await t.attr("#sa", "data-overflow-x")) + " " + (await t.attr("#sa", "data-at-start")), "  ")
  t.eq("scrollbars are hidden from assistive technology, each with its orientation", (await t.attr("#sa-y", "aria-hidden")) + " " + (await t.attr("#sa-y", "data-orientation")) + " " + (await t.attr("#sa-x-thumb", "data-orientation")), "true vertical horizontal")
  t.check("the thumb is sized to the view", (await t.page.locator("#sa-y-thumb").evaluate((el) => el.getBoundingClientRect().height)) > 5, "")
  t.eq("the corner shows where both scrollbars meet", await t.page.locator("#sa-corner").evaluate((el) => getComputedStyle(el).display !== "none"), true)
  await t.page.focus("#sa-viewport")
  await t.press("End")
  await t.settle(300)
  t.check("the keyboard scrolls the viewport", (await top()) > 100, String(await top()))
  t.eq("at the end: says so, and the end button is inert", (await t.attr("#sa", "data-at-end")) + " " + (await t.attr("#sa-end", "inert")), " ")
  await t.page.locator("#sa-viewport").evaluate((el) => el.scrollTo({ top: 0 }))
  await t.settle(300)
  t.eq("back at the top: the end button shows", (await t.attr("#sa-end", "data-visible")) + " " + (await t.attr("#sa-end", "inert")), " null")
  await t.page.click("#sa-end")
  await t.settle(600)
  t.check("the end button scrolls to the end", (await top()) > 100, String(await top()))
  await t.page.locator("#sa-viewport").evaluate((el) => el.scrollTo({ top: 0, behavior: "instant" }))
  await t.settle(200)
  const thumb = await t.page.locator("#sa-y-thumb").boundingBox()
  await t.page.mouse.move(thumb.x + 5, thumb.y + 5)
  await t.page.mouse.down()
  t.eq("pressing the thumb drags it", await t.attr("#sa-y-thumb", "data-dragging"), "")
  await t.page.mouse.move(thumb.x + 5, thumb.y + 45, { steps: 5 })
  await t.page.mouse.up()
  await t.settle(200)
  t.check("dragging the thumb scrolls the viewport", (await top()) > 50, String(await top()))
}
