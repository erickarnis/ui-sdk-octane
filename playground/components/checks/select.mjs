export default async function select(t) {
  const { page } = t
  t.eq("the trigger is a combobox named by the label, closed", [await t.attr("#s-trigger", "role"), await t.attr("#s-trigger", "aria-labelledby"), await t.attr("#s-trigger", "aria-expanded")].join(" "), "combobox s-label false")
  t.eq("closed, it shows the default value's label and icon, learned from the markup", (await t.text("#s-value")) + " " + (await t.text("#s-value-icon")), "Banana B")
  t.eq("a select whose content is not mounted shows its default's label from its markup", (await t.text("#l-trigger")) + " " + (await t.count("#l-content")), "Row 3 0")
  t.eq("closed content is hidden", await t.visible("#s-content"), false)
  await page.click("#s-label")
  t.eq("pressing the label focuses the trigger", await t.active(), "s-trigger")
  await t.press("ArrowDown")
  t.eq("ArrowDown opens a listbox named by the label, in the top layer", [await t.attr("#s-trigger", "aria-expanded"), await t.attr("#s-content", "role"), await t.attr("#s-content", "aria-labelledby"), await page.locator("#s-content").evaluate((el) => el.matches(":popover-open"))].join(" "), "true listbox s-label true")
  t.eq("the selected item is highlighted", await t.attr("#s-banana", "data-highlighted"), "")
  t.eq("focus goes to the selected item", await t.active(), "s-banana")
  await t.press("ArrowDown")
  t.eq("ArrowDown skips a disabled item", await t.attr("#s-lemon", "data-highlighted"), "")
  await t.press("End")
  t.eq("End highlights the last item", await t.attr("#s-lime", "data-highlighted"), "")
  await t.press("Home")
  t.eq("Home highlights the first item", await t.attr("#s-apple", "data-highlighted"), "")
  await t.press("l")
  await t.press("i")
  t.eq("typeahead highlights the match", await t.attr("#s-lime", "data-highlighted"), "")
  await t.press("Enter")
  t.eq("Enter selects, closes and returns focus", [await t.text("#s-value"), await t.visible("#s-content"), await t.active()].join(" "), "Lime false s-trigger")
  t.eq("the icon follows the value: none for an item without one", await t.count("#s-value-icon"), 0)
  await t.settle(600)
  await t.press("a")
  t.eq("typing on the closed trigger selects the match", (await t.text("#s-value")) + " " + (await t.visible("#s-content")), "Apple false")
  await page.click("#s-trigger")
  t.eq("a click opens it, the indicator shows on the selected item", (await t.visible("#s-content")) + " " + (await t.count("#s-apple-check")), "true 1")
  const box = await page.evaluate(() => {
    const trigger = document.getElementById("s-trigger").getBoundingClientRect()
    const content = document.getElementById("s-content").getBoundingClientRect()
    return Math.round(content.top - trigger.bottom)
  })
  t.eq("positioned below the trigger by the side offset", box, 4)
  await page.click("#s-cherry", { force: true })
  t.eq("a disabled item ignores a click", (await t.visible("#s-content")) + " " + (await t.text("#s-value")), "true Apple")
  await page.click("#s-banana")
  t.eq("a click selects and closes", (await t.text("#s-value")) + " " + (await t.visible("#s-content")), "Banana false")
  await page.click("#s-trigger")
  await t.press("Escape")
  t.eq("Escape closes and returns focus", (await t.visible("#s-content")) + " " + (await t.active()), "false s-trigger")
  await page.click("#s-trigger")
  await page.click("#s-after")
  await t.settle()
  t.eq("a click outside closes it, and focus returns to the trigger as focus leaves", (await t.visible("#s-content")) + " " + (await t.active()), "false s-trigger")
  await page.click("#s-form-submit")
  t.eq("it submits its value under its name", await t.text("#s-form-sent"), "fruit=banana")
  await page.click("#s-trigger")
  await page.click("#s-lemon")
  await page.click("#s-form-reset")
  await t.settle()
  t.eq("a form reset restores the default", await t.text("#s-value"), "Banana")

  t.eq("multiple from data: closed, it shows the value's label", await t.text("#m-trigger"), "Venus")
  await page.click("#m-trigger")
  const content = "#" + (await t.attr("#m-trigger", "aria-controls")).replaceAll(":", "\\:")
  const options = content + " [role=option]"
  t.eq("data: the content renders the items in groups", (await t.count(options)) + " " + (await t.count(content + " [role=group]")) + " " + (await t.attr(content, "aria-multiselectable")), "4 2 true")
  await page.locator(options).nth(2).click()
  t.eq("multiple: a click adds and stays open", (await t.text("#m-value")) + " " + (await t.count(options)), "venus,jupiter 4")
  await page.locator(options).nth(1).click()
  t.eq("multiple: a click on a selected item removes it", await t.text("#m-value"), "jupiter")
  await t.press("Escape")
  await page.click("#m-set")
  t.eq("controlled: a value set from outside shows in the trigger", await t.text("#m-trigger"), "Jupiter, Saturn")
  await page.click("#m-form-submit")
  t.eq("multiple: every value submits", await t.text("#m-form-sent"), "planet=jupiter&planet=saturn")
  await page.click("#m-clear")
  t.eq("clear selects nothing and shows the placeholder", (await t.text("#m-value")) + "|" + (await t.text("#m-trigger")), "|Planets")

  await page.click("#q-trigger")
  await t.settle()
  t.eq("search: focus moves to the input", await t.active(), "q-input")
  await page.keyboard.type("an")
  await t.settle()
  t.eq("typing filters the list", (await page.locator("#q-list [role=option]:visible").allTextContents()).join(","), "France,Germany,Ireland")
  t.eq("the match is marked", await page.locator("#q-France mark").first().textContent(), "an")
  await t.press("ArrowDown")
  t.eq("arrows move the highlight while focus stays in the input", (await t.active()) + " " + (await t.attr("#q-input", "aria-activedescendant")), "q-input q-Germany")
  await t.press("Enter")
  t.eq("Enter selects the highlighted match", (await t.text("#q-value")) + " " + (await t.visible("#q-content")), "Germany false")
  await page.click("#q-trigger")
  await t.settle()
  await page.keyboard.type("zz")
  await t.settle()
  t.eq("no match shows the empty part", (await t.count("#q-list [role=option]:visible")) + " " + (await t.text("#q-empty")), "0 No country")
  await t.press("Escape")

  await page.click("#a-trigger")
  await page.click("#a-all")
  t.eq("select all selects every item", await t.attrs("#a-content [role=option]", "aria-selected"), "true,true,true")
  await page.click("#a-all")
  t.eq("and again selects none", await t.attrs("#a-content [role=option]", "aria-selected"), "false,false,false")
  await t.press("Escape")

  await page.click("#l-trigger")
  await t.settle()
  await t.press("End")
  t.eq("a long list: End highlights the last row and scrolls to it", (await t.attr("#l-40", "data-highlighted")) + " " + (await page.locator("#l-content").evaluate((el) => el.scrollTop > 0)), " true")
  await t.press("Escape")
  await page.click("#l-fewer")
  await page.click("#l-trigger")
  await t.settle()
  await t.press("End")
  t.eq("a list that shrinks: its keys see the new list", (await t.count("#l-content [role=option]")) + " " + (await t.attr("#l-4", "data-highlighted")), "4 ")
  await t.press("Escape")

  t.eq("in a field: the field's label names the trigger, the field's name submits", (await t.attr("#f-trigger", "aria-labelledby")) + " " + (await t.attr("#page-select [data-slot=field] textarea", "name")), "f-label size")
}
