export default async function menu(t) {
  const { page } = t
  t.eq("trigger names its popup kind and is closed", [await t.attr("#m-trigger", "aria-haspopup"), await t.attr("#m-trigger", "aria-expanded")].join(" "), "menu false")
  t.eq("closed content is not in the page", await t.count("#m"), 0)
  await page.locator("#m-trigger").focus()
  await t.press("Enter")
  t.eq("Enter opens it, labelled by its trigger", [await t.count("#m"), await t.attr("#m", "role"), await t.attr("#m", "aria-labelledby"), await t.attr("#m-trigger", "aria-controls")].join(" "), "1 menu m-trigger m")
  t.eq("in the top layer", await page.locator("#m").evaluate((el) => el.matches(":popover-open")), true)
  t.eq("opening with the keyboard focuses the first item", await t.active(), "m-cut")
  t.eq("roles of the items", [await t.attr("#m-cut", "role"), await t.attr("#m-bold", "role"), await t.attr("#m-small", "role"), await t.attr("#m-sep", "role"), await t.attr("#m-group", "role")].join(" "), "menuitem menuitemcheckbox menuitemradio separator group")
  t.eq("a group is named by its label", await t.attr("#m-group", "aria-labelledby"), "m-group-label")
  t.eq("a shortcut is announced and shown", [await t.attr("#m-cut", "aria-keyshortcuts"), await t.attr("#m-cut [data-slot=menu-shortcut]", "aria-hidden")].join(" "), "Control+X true")
  await t.press("ArrowDown")
  t.eq("ArrowDown moves to the next item", await t.active(), "m-copy")
  await t.press("ArrowDown")
  t.eq("a disabled item is focusable, as the menu pattern asks", [await t.active(), await t.attr("#m-disabled", "aria-disabled")].join(" "), "m-disabled true")
  await t.press("Enter")
  t.eq("and does nothing when chosen", [await t.text("#m-last"), await t.count("#m")].join(" "), "none 1")
  await t.press("End")
  t.eq("End moves to the last item", await t.active(), "m-share")
  await t.press("Home")
  t.eq("Home moves to the first item", await t.active(), "m-cut")
  await t.press("ArrowUp")
  t.eq("ArrowUp wraps to the last item", await t.active(), "m-share")
  await t.press("b")
  t.eq("typeahead moves to the item starting with the letter", await t.active(), "m-bold")
  await t.press("Space")
  t.eq("a checkbox item toggles and keeps the menu open with closeOnSelect false", [await t.text("#m-bold-out"), await t.attr("#m-bold", "aria-checked"), await t.count("#m"), await t.count("#m-bold-indicator")].join(" "), "true true 1 1")
  await page.click("#m-small")
  await t.settle()
  t.eq("a radio item checks its value, and the menu stays open", [await t.text("#m-size-out"), await t.attr("#m-small", "aria-checked"), await t.attr("#m-medium", "aria-checked"), await t.count("#m")].join(" "), "s true false 1")
  await t.press("Escape")

  await t.press("ArrowDown")
  t.eq("ArrowDown on the trigger opens it", await t.count("#m"), 1)
  await t.press("End")
  t.eq("a submenu trigger is a menu item that names its popup", [await t.attr("#m-share", "aria-haspopup"), await t.attr("#m-share", "aria-expanded")].join(" "), "menu false")
  await t.press("ArrowRight")
  t.eq("ArrowRight opens the submenu and focuses its first item", [await t.count("#m-sub"), await t.active(), await t.attr("#m-share", "aria-expanded")].join(" "), "1 m-email true")
  await t.press("ArrowLeft")
  t.eq("ArrowLeft closes the submenu and returns to its trigger", [await t.count("#m-sub"), await t.active()].join(" "), "0 m-share")
  await t.press("Enter")
  await t.press("ArrowDown")
  t.eq("Enter opens the submenu too", await t.active(), "m-link")
  await t.press("Enter")
  await t.settle()
  t.eq("choosing a submenu item runs it and closes every menu", [await t.text("#m-last"), await t.count("#m"), await t.count("#m-sub"), await t.active()].join(" "), "link 0 0 m-trigger")

  await t.press("Enter")
  await t.press("ArrowDown")
  await t.press("Enter")
  t.eq("Enter runs the focused item", [await t.text("#m-last"), await t.count("#m")].join(" "), "copy 0")
  await t.press("Enter")
  await t.press("Escape")
  t.eq("Escape closes it and returns focus to the trigger", [await t.count("#m"), await t.active()].join(" "), "0 m-trigger")
  await page.click("#m-trigger")
  await page.hover("#m-share")
  await page.waitForTimeout(400)
  t.eq("hovering the submenu trigger opens the submenu", await t.count("#m-sub"), 1)
  await page.click("#m-email")
  await t.settle()
  t.eq("clicking a submenu item runs it", [await t.text("#m-last"), await t.count("#m")].join(" "), "email 0")
  await page.click("#m-trigger")
  await page.click("#m-after")
  await t.settle()
  t.eq("an outside press closes it", await t.count("#m"), 0)

  await page.click("#d-trigger")
  t.eq("a data menu renders its content from items", [await t.count("[data-slot=menu-content]"), await t.count("[data-slot=menu-content] [role=menuitem]"), await t.count("[data-slot=menu-content] [role=separator]")].join(" "), "1 2 1")
  await page.locator("[data-slot=menu-content] [role=menuitem]", { hasText: "Close" }).click()
  await t.settle()
  t.eq("a data item reaches onAction", await t.text("#m-last"), "data:close")

  await page.click("#c-trigger")
  t.eq("controlled: a press reaches the app and opens", [await t.text("#c-open"), await t.count("#c")].join(" "), "true 1")
  await t.press("Escape")
  await t.settle()
  t.eq("controlled: Escape asks the app to close", [await t.text("#c-open"), await t.count("#c")].join(" "), "false 0")
  await page.click("#c-outside")
  t.eq("controlled: the app opens it from outside", [await t.count("#c"), await t.attr("#c-trigger", "aria-expanded")].join(" "), "1 true")
  await t.press("Escape")
  await t.settle()

  await page.click("#x-area", { button: "right", position: { x: 50, y: 30 } })
  t.eq("a right-click on the context area opens its menu", await t.count("#x"), 1)
  const where = await page.evaluate(() => {
    const area = document.getElementById("x-area").getBoundingClientRect()
    const menu = document.getElementById("x").getBoundingClientRect()
    return Math.abs(menu.left - (area.left + 50)) < 8 && Math.abs(menu.top - (area.top + 30)) < 8
  })
  t.eq("at the pointer", where, true)
  await page.click("#x-reload")
  await t.settle()
  t.eq("its item runs", [await t.text("#m-last"), await t.count("#x")].join(" "), "reload 0")
  // A browser fires a keyboard context menu event, which Playwright can't press, for Shift+F10.
  await page.locator("#x-area").evaluate((el) => el.dispatchEvent(new MouseEvent("contextmenu", { bubbles: true, cancelable: true, button: 0 })))
  await t.settle()
  t.eq("a keyboard context menu event opens it and focuses its first item", [await t.count("#x"), await t.active()].join(" "), "1 x-reload")
  await t.press("Escape")

  await page.click("#r-trigger")
  t.eq("a trigger outside the menu opens it through the controller", [await t.count("#r"), await t.attr("#r-trigger", "aria-expanded")].join(" "), "1 true")
  await t.press("Escape")
  t.eq("and takes focus back", await t.active(), "r-trigger")
}
