export default async function shortcutsChecks(t) {
  t.eq("the hint is formatted for this platform, with aria-keyshortcuts", (await t.text("#search-hint")).replace(/[⁦-⁩]/g, "") + " " + (await t.attr("#search-hint", "aria-keyshortcuts")), "Ctrl+K Control+K")
  await t.page.locator("body").click({ position: { x: 1, y: 1 } })
  await t.press("Control+k")
  await t.press("Control+k")
  t.eq("the shortcut runs its latest handler", await t.text("#search-count"), "2")
  await t.page.focus("#field")
  await t.press("Control+k")
  t.eq("a modified shortcut still runs in a text field", await t.text("#search-count"), "3")
  await t.page.click("#search-toggle")
  await t.press("Control+k")
  t.eq("when false, it doesn't run", await t.text("#search-count"), "3")
  await t.page.click("#search-toggle")
  await t.page.click("#list")
  t.eq("registered while mounted", await t.text("#listed"), "mod+k,x")
  await t.page.click("#unmount")
  await t.page.click("#list")
  t.eq("unmounted, it's unregistered", await t.text("#listed"), "x")
  await t.page.locator("body").click({ position: { x: 1, y: 1 } })
  await t.press("x")
  t.eq("a shortcut in a layer given by a ref runs while nothing covers it", await t.text("#layer-count"), "1")
  t.eq("formatShortcut resolves", (await t.text("#formatted")).replace(/[⁦-⁩]/g, ""), "Shift+A")
}
