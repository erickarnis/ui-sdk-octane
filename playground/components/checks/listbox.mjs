export default async function listbox(t) {
  const { page } = t
  t.eq("a listbox named by its label, with options", [await t.attr("#lb", "role"), await t.attr("#lb", "aria-labelledby"), await t.count("#lb [role=option]")].join(" "), "listbox lb-label 5")
  t.eq("a group named by its label, a separator hidden", (await t.attr("#lb-warm", "aria-labelledby")) + " " + (await t.attr("#lb-sep", "aria-hidden")), "lb-warm-label true")
  t.eq("the default value is selected and is the tab stop", (await t.attr("#lb-green", "aria-selected")) + " " + (await t.attrs("#lb [role=option]", "tabindex")), "true -1,-1,0,-1,-1")
  t.eq("the indicator is absent while unselected", await t.count("#lb-red-check"), 0)
  await page.locator("#lb-green").focus()
  await t.press("ArrowDown")
  t.eq("ArrowDown moves focus", await t.active(), "lb-blue")
  await t.press("ArrowUp")
  await t.press("ArrowUp")
  t.eq("ArrowUp skips the disabled option", await t.active(), "lb-red")
  await t.press("End")
  t.eq("End moves to the last option", await t.active(), "lb-black")
  await t.press("Home")
  t.eq("Home moves to the first option", await t.active(), "lb-red")
  await t.press("b")
  await t.press("l")
  t.eq("typeahead moves to the matching option", await t.active(), "lb-blue")
  await t.settle(600)
  await t.press("b")
  await t.press("b")
  t.eq("repeating a letter cycles through its options", await t.active(), "lb-blue")
  await t.press("Space")
  t.eq("Space selects the focused option, alone", await t.attrs("#lb [role=option]", "aria-selected"), "false,false,false,true,false")
  await page.click("#lb-red")
  t.eq("a click selects an option and shows its indicator", (await t.attr("#lb-red", "aria-selected")) + " " + (await t.count("#lb-red-check")), "true 1")
  await page.click("#lb-orange", { force: true })
  t.eq("a click on a disabled option does nothing", await t.attr("#lb-orange", "aria-selected"), "false")
  await page.click("#lb-form-submit")
  t.eq("it submits its value under its name", await t.text("#lb-form-sent"), "colour=red")
  await page.click("#lb-form-reset")
  await t.settle()
  t.eq("a form reset restores the default", await t.attr("#lb-green", "aria-selected"), "true")
  await page.click("#lb-blue")
  await page.locator("#lb-blue").focus()
  await t.press("Tab")
  t.eq("Tab leaves the listbox", await t.active(), "lb-form-submit")

  t.eq("multiple: a multiselectable listbox from data, with groups", [await t.attr("#mlb", "aria-multiselectable"), await t.count("#mlb [role=group]"), await t.count("#mlb [role=option]")].join(" "), "true 2 5")
  t.eq("the data's labels name its groups", await t.text("#mlb [role=group] [data-slot=listbox-group-label]"), "Inner")
  const options = "#mlb [role=option]"
  await page.locator(options).nth(0).click()
  t.eq("multiple: a click adds to the value", await t.text("#mlb-value"), "venus,mercury")
  await page.locator(options).nth(1).click()
  t.eq("multiple: a click on a selected option removes it", await t.text("#mlb-value"), "mercury")
  await page.locator(options).nth(2).click()
  await page.click("#mlb-form-submit")
  t.eq("multiple: every value submits under the name", await t.text("#mlb-form-sent"), "planet=mercury&planet=jupiter")
  await page.click("#mlb-set")
  t.eq("controlled: a value set from outside reaches the options", await t.attrs(options, "aria-selected"), "true,false,true,false,false")
  await page.locator(options).nth(0).focus()
  await t.press("Shift+ArrowDown")
  t.eq("Shift+ArrowDown moves and selects", await t.text("#mlb-value"), "jupiter,mercury,venus")
  await t.press("Control+a")
  t.eq("Control+A selects every enabled option", await t.attrs(options, "aria-selected"), "true,true,true,false,true")

  await page.click("#olb-2")
  t.eq("objects: the value is the item, matched by its id", (await t.text("#olb-value")) + " " + (await t.attrs("#olb [role=option]", "aria-selected")), "Banana false,true,false")
  await t.press("ArrowDown")
  await t.press("Enter")
  t.eq("objects: Enter selects the focused item", await t.text("#olb-value"), "Cherry")

  await page.locator("#llb-1").focus()
  await t.press("End")
  t.eq("a long list: End reaches the last option and scrolls it into view", (await t.active()) + " " + (await page.locator("#llb").evaluate((el) => el.scrollTop > 0)), "llb-30 true")
  await page.click("#llb-fewer")
  await t.settle()
  t.eq("a list that shrinks keeps one tab stop", (await t.count("#llb [role=option]")) + " " + (await t.count('#llb [tabindex="0"]')), "5 1")
  await page.locator("#llb-3").focus()
  await t.press("End")
  t.eq("and its keys see the new list", await t.active(), "llb-5")

  t.eq("in a field: named by the field's label", (await t.attr("#flb", "aria-labelledby")) + " " + (await t.attr("#page-listbox [data-slot=field] textarea", "name")), "flb-label size")
}
