export default async function sliderChecks(t) {
  const input = "#sl-thumb input[type=range]"
  t.eq("a thumb holds a native range input, named", (await t.count(input)) + " " + (await t.attr(input, "aria-label")) + " " + (await t.page.inputValue(input)), "1 Volume 30")
  t.eq("the value shows formatted", await t.text("#sl-value"), "30")
  t.check("the thumb sits at its position", ((await t.attr("#sl-thumb", "style")) ?? "").includes("30%"), await t.attr("#sl-thumb", "style"))
  await t.page.focus(input)
  await t.press("ArrowRight")
  await t.press("ArrowRight")
  t.eq("ArrowRight steps up", (await t.page.inputValue(input)) + " " + (await t.text("#sl-value")), "32 32")
  await t.press("PageUp")
  t.eq("PageUp steps by the large step", await t.page.inputValue(input), "42")
  await t.press("Home")
  t.eq("Home goes to the minimum", await t.page.inputValue(input), "0")
  const box = await t.page.locator("#sl-control [data-slot=slider-track]").boundingBox()
  await t.page.mouse.click(box.x + box.width * 0.75, box.y + box.height / 2)
  await t.settle()
  t.check("a press on the control moves the thumb there", Math.abs(Number(await t.page.inputValue(input)) - 75) <= 4, await t.page.inputValue(input))
  t.eq("and focuses it", await t.page.evaluate(() => document.activeElement?.type), "range")
  await t.page.click("#sl-form-submit")
  t.check("the hidden input submits the value", /^volume=\d+$/.test(await t.text("#sl-form-sent")), await t.text("#sl-form-sent"))

  t.eq("range: a named group, two thumbs", (await t.attr("#rs", "role")) + " " + (await t.attr("#rs", "aria-label")) + " " + (await t.count("#rs input[type=range]")), "group Price 2")
  t.eq("range: the value joins the ends with an en dash", await t.text("#rs-value"), "$20 – $60")
  await t.page.locator("#rs input[type=range]").nth(1).focus()
  await t.press("End")
  t.eq("range: a key reaches the app, and the commit too", await t.text("#rs-state"), "20-100|20-100")
  await t.page.locator("#rs input[type=range]").first().focus()
  await t.press("End")
  t.eq("range: thumbs keep the minimum steps apart", await t.text("#rs-state").then((s) => s.split("|")[0]), "90-100")
  await t.page.click("#rs-outside")
  t.eq("range: a value from outside shows", (await t.text("#rs-value")) + " " + (await t.page.inputValue("#rs input[type=range] >> nth=0")), "$0 – $100 0")

  t.eq("in a field: the thumb's input is named by the label", await t.attr("#fsl-thumb input[type=range]", "aria-labelledby"), "fsl-label")
  t.eq("in a field: the hidden input takes the field's name", await t.page.locator("#fsl-thumb").evaluate((el) => el.closest("[data-slot=slider]").querySelector("input:not([type=range])").name), "brightness")
}
