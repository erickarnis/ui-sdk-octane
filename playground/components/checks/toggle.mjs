export default async function toggle(t) {
  t.eq("starts unpressed", await t.attr("#tg", "aria-pressed"), "false")
  await t.page.click("#tg")
  t.eq("click presses", await t.attr("#tg", "aria-pressed"), "true")
  await t.press("Space")
  t.eq("Space unpresses", await t.attr("#tg", "aria-pressed"), "false")
  await t.press("Enter")
  t.eq("Enter presses", await t.attr("#tg", "aria-pressed"), "true")
  t.eq("keeps its name and hides its icon from screen readers", (await t.attr("#tg", "aria-label")) + " " + (await t.attr("#tg [data-slot=toggle-icon]", "aria-hidden")), "Bold true")
  await t.page.click("#ctg")
  t.eq("controlled: press reaches the app and shows", (await t.text("#ctg-value")) + " " + (await t.text("#ctg")), "true On")
  await t.page.click("#ctg-outside")
  t.eq("controlled: change from outside shows", await t.attr("#ctg", "aria-pressed"), "false")
  t.eq("disabled toggle can't be pressed", await t.attr("#dtg", "disabled"), "")

  const group = "#tgg button"
  t.eq("the group is named", (await t.attr("#tgg", "role")) + " " + (await t.attr("#tgg", "aria-label")), "group Alignment")
  t.eq("the group's value presses its toggle from the first render", await t.attrs(group, "aria-pressed"), "true,false,false")
  t.eq("only one toggle is a tab stop", await t.attrs(group, "tabindex"), "0,-1,-1")
  await t.page.locator("#tgg-left").focus()
  await t.press("ArrowRight")
  t.eq("ArrowRight moves focus without pressing", (await t.active()) + " " + (await t.attrs(group, "aria-pressed")), "tgg-center true,false,false")
  await t.press("Space")
  t.eq("Space presses the focused toggle and unpresses the other", (await t.attrs(group, "aria-pressed")) + " " + (await t.text("#tgg-value")), "false,true,false center")
  await t.press("End")
  t.eq("End moves to the last", await t.active(), "tgg-right")
  await t.press("ArrowRight")
  t.eq("focus wraps", await t.active(), "tgg-left")
  await t.press("ArrowDown")
  t.eq("ArrowDown does nothing in a horizontal group", await t.active(), "tgg-left")
  await t.press("Tab")
  t.eq("Tab leaves the group", await t.active(), "tgg-set")
  await t.page.keyboard.press("Shift+Tab")
  t.eq("and returns to the toggle focused last", await t.active(), "tgg-left")
  await t.page.click("#tgg-set")
  t.eq("a value from outside presses its toggle", await t.attrs(group, "aria-pressed"), "false,false,true")
  await t.page.click("#tgg-right")
  t.eq("pressing the pressed toggle unpresses it", (await t.attrs(group, "aria-pressed")) + "|" + (await t.text("#tgg-value")), "false,false,false|")

  t.eq("a vertical group carries its orientation", await t.attr("#mtgg", "data-orientation"), "vertical")
  await t.page.click("#mtgg-italic")
  t.eq("multiple: pressing adds to the value", await t.attrs("#mtgg button", "aria-pressed"), "true,true")
  await t.press("ArrowUp")
  t.eq("vertical: ArrowUp moves", await t.active(), "mtgg-bold")
}
