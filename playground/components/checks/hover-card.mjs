export default async function hoverCard(t) {
  const { page } = t
  t.eq("a link trigger, closed", [await page.locator("#hc-trigger").evaluate((el) => el.tagName), await t.attr("#hc-trigger", "href"), await t.count("#hc")].join(" "), "A #profile 0")
  await page.hover("#hc-trigger")
  await t.settle(60)
  t.eq("waits for its delay", await t.count("#hc"), 0)
  await t.settle(300)
  t.eq("resting the pointer on the trigger opens it", await t.count("#hc"), 1)
  t.eq("in the top layer, and focus stays where it was", [await page.locator("#hc").evaluate((el) => el.matches(":popover-open")), await t.active()].join(" "), "true body")
  const below = await page.evaluate(() => Math.round(document.getElementById("hc").getBoundingClientRect().top - document.getElementById("hc-trigger").getBoundingClientRect().bottom))
  t.eq("below its trigger by the side offset, with the arrow on that side", [below, await t.attr("#hc-arrow", "data-side")].join(" "), "6 bottom")
  await page.hover("#hc-link")
  await t.settle(300)
  t.eq("the pointer can move onto the card", await t.count("#hc"), 1)
  await page.mouse.move(900, 600)
  await t.settle(80)
  t.eq("leaving waits for the close delay", await t.count("#hc"), 1)
  await t.settle(400)
  t.eq("then closes", await t.count("#hc"), 0)

  await page.locator("#hc-before").focus()
  await t.press("Tab")
  await t.settle(400)
  t.eq("keyboard focus on the trigger opens it", [await t.count("#hc"), await t.active()].join(" "), "1 hc-trigger")
  await t.press("Escape")
  await t.settle()
  t.eq("Escape closes it", [await t.count("#hc"), await t.active()].join(" "), "0 hc-trigger")
  await t.press("Tab")
  await t.settle(400)
  t.eq("focus leaving closes it", await t.count("#hc"), 0)
  await page.locator("#hc-before").focus()
  await t.settle(400)

  await page.hover("#chc-trigger")
  await t.settle(150)
  t.eq("controlled: hover asks the app to open", [await t.text("#chc-open"), await t.count("#chc")].join(" "), "true 1")
  await page.mouse.move(900, 10)
  await t.settle(500)
  t.eq("controlled: leaving asks the app to close", [await t.text("#chc-open"), await t.count("#chc")].join(" "), "false 0")
  await page.click("#chc-outside")
  t.eq("controlled: the app opens it", await t.count("#chc"), 1)
  await page.mouse.move(900, 10)

  await page.hover("#rhc-trigger")
  await t.settle(150)
  t.eq("a trigger outside the card opens it through the controller", await t.count("#rhc"), 1)
}
