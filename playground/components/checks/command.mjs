export default async function command(t) {
  const { page } = t
  const shown = (list) => page.locator(list + " [role=option]:visible").evaluateAll((els) => els.map((el) => el.id || el.textContent).join(","))
  t.eq("an always-open list: the input controls the listbox and highlights the first command", [await t.attr("#cmd-input", "role"), await t.attr("#cmd-input", "aria-controls"), await t.attr("#cmd-input", "aria-activedescendant"), await t.attr("#cmd-list", "role")].join(" "), "combobox cmd-list cmd-copy listbox")
  t.eq("a shortcut is shown for the platform and given to screen readers", (await t.attr("#cmd-copy", "aria-keyshortcuts")) + " " + (await t.text("#cmd-copy-keys")).replace(/[⁦⁩]/g, ""), "Control+Shift+C Ctrl+Shift+C")
  t.eq("only the first page shows", await shown("#cmd-list"), "cmd-copy,cmd-paste,cmd-cut,cmd-theme")
  await page.focus("#cmd-input")
  await t.press("ArrowDown")
  t.eq("ArrowDown skips a disabled command, focus stays in the input", (await t.attr("#cmd-input", "aria-activedescendant")) + " " + (await t.active()), "cmd-cut cmd-input")
  await t.press("ArrowDown")
  t.eq("ArrowDown moves into the next group", await t.attr("#cmd-input", "aria-activedescendant"), "cmd-theme")
  await t.press("ArrowUp")
  await t.press("Enter")
  t.eq("Enter runs the highlighted command", await t.text("#cmd-ran"), "cut")
  await page.keyboard.type("remove")
  await t.settle()
  t.eq("typing filters by label and keywords, hiding empty groups", [await shown("#cmd-list"), await t.visible("#cmd-g2"), await t.text("#cmd-query")].join(" "), "cmd-cut false remove")
  await page.fill("#cmd-input", "copy")
  await t.settle()
  t.eq("the match is marked", await page.locator("#cmd-copy mark").first().textContent(), "Copy")
  await page.fill("#cmd-input", "zzz")
  await t.settle()
  t.eq("no match shows the empty part", (await shown("#cmd-list")) + "|" + (await t.text("#cmd-empty")), "|Nothing found")
  await page.click("#cmd-set")
  await t.settle()
  t.eq("controlled: a query set from outside filters", (await page.inputValue("#cmd-input")) + " " + (await shown("#cmd-list")), "cu cmd-cut")
  await page.fill("#cmd-input", "")
  await t.settle()
  await page.click("#cmd-copy")
  t.eq("a click runs a command", await t.text("#cmd-ran"), "copy")
  await page.focus("#cmd-input")
  await page.click("#cmd-theme")
  await t.settle()
  t.eq("a command with a page opens it", await shown("#cmd-list"), "cmd-dark,cmd-light")
  await page.focus("#cmd-input")
  await t.press("ArrowDown")
  await t.press("Enter")
  t.eq("a page's command runs", await t.text("#cmd-ran"), "light")
  await t.press("Backspace")
  await t.settle()
  t.eq("Backspace in the empty input goes back a page", await shown("#cmd-list"), "cmd-copy,cmd-paste,cmd-cut,cmd-theme")

  const dlist = "#" + (await t.attr("#dcmd-input", "aria-controls")).replaceAll(":", "\\:")
  t.eq("data: commands render in groups", (await shown(dlist)).split(",").length + " " + (await t.count(dlist + " [role=group]")), "3 1")
  await page.focus("#dcmd-input")
  await page.keyboard.type("sav")
  await t.press("Enter")
  t.eq("data: typing and Enter run the match", await t.text("#dcmd-ran"), "save")
  await page.fill("#dcmd-input", "")
  await t.press("Control+o")
  t.eq("data: a command's shortcut runs it", await t.text("#dcmd-ran"), "open")
}
