export default async function toolbar(t) {
  t.eq("a named, horizontal toolbar", [await t.attr("#tb", "role"), await t.attr("#tb", "aria-label"), await t.attr("#tb", "aria-orientation")].join(" "), "toolbar Formatting horizontal")
  await t.page.locator("#before").focus()
  await t.press("Tab")
  t.eq("Tab lands on the first item", await t.active(), "tb-undo")
  await t.press("Tab")
  t.eq("Tab again leaves the toolbar", await t.active(), "after")
  await t.page.keyboard.press("Shift+Tab")
  t.eq("Shift+Tab lands on its tab stop", await t.active(), "tb-undo")
  const walk = []
  for (let i = 0; i < 8; i++) {
    await t.press("ArrowRight")
    walk.push(await t.active())
  }
  t.eq("ArrowRight moves through every item, into the toggle group, past the disabled group, and wraps", walk.join(" "), "tb-redo tb-bold tb-left tb-right tb-locked tb-link tb-input tb-undo")
  t.eq("a disabled button stays reachable and says it's disabled", await t.attr("#tb-redo", "aria-disabled"), "true")
  t.eq("items in a disabled group are disabled", await t.attr("#tb-locked", "aria-disabled"), "true")
  t.eq("the separator runs across the toolbar", [await t.attr("#tb-sep", "role"), await t.attr("#tb-sep", "aria-orientation")].join(" "), "separator vertical")
  await t.press("ArrowLeft")
  t.eq("ArrowLeft on the first wraps to the last", await t.active(), "tb-input")
  await t.press("Home")
  t.eq("a text field keeps Home for its caret", await t.active(), "tb-input")
  await t.press("ArrowLeft")
  t.eq("at its start, ArrowLeft leaves the field", await t.active(), "tb-link")
  await t.page.locator("#tb-bold").focus()
  t.eq("arrows never pressed the toggle", await t.attr("#tb-bold", "aria-pressed"), "false")
  await t.press("Space")
  t.eq("Space presses it", await t.attr("#tb-bold", "aria-pressed"), "true")
  await t.press("ArrowRight")
  await t.press("ArrowRight")
  await t.press("Enter")
  t.eq("Enter presses a toggle in the group", await t.attrs("#tb-align button", "aria-pressed"), "false,true")
  t.eq("the toolbar has one tab stop", await t.page.locator("#tb [tabindex='0']").count(), 1)
  await t.press("Tab")
  await t.page.keyboard.press("Shift+Tab")
  t.eq("Tab comes back to the item focused last", await t.active(), "tb-right")
}
