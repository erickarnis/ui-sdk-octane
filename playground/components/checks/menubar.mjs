export default async function menubar(t) {
  const { page } = t
  t.eq("a menubar with its triggers as menu items", [await t.attr("#mb", "role"), await t.attr("#mb", "aria-orientation"), await t.attrs("#mb [data-slot=menu-trigger]", "role")].join(" "), "menubar horizontal menuitem,menuitem,menuitem")
  t.eq("one tab stop", await t.attrs("#mb [data-slot=menu-trigger]", "tabindex"), "0,-1,-1")
  await page.locator("#mb-before").focus()
  await t.press("Tab")
  t.eq("Tab enters at the first trigger", await t.active(), "mb-file")
  await t.press("ArrowRight")
  t.eq("ArrowRight moves to the next trigger without opening", [await t.active(), await t.count("#mb-file-menu, #mb-edit-menu")].join(" "), "mb-edit 0")
  t.eq("the tab stop follows focus", await t.attrs("#mb [data-slot=menu-trigger]", "tabindex"), "-1,0,-1")
  await t.press("ArrowRight")
  await t.press("ArrowRight")
  t.eq("ArrowRight wraps to the first trigger", await t.active(), "mb-file")
  await t.press("ArrowLeft")
  t.eq("ArrowLeft wraps to the last", await t.active(), "mb-view")
  await t.press("Home")
  t.eq("Home moves to the first trigger", await t.active(), "mb-file")
  await t.press("Tab")
  t.eq("Tab leaves the menubar", await t.active(), "mb-after")
  await page.keyboard.press("Shift+Tab")
  t.eq("and Shift+Tab comes back to the trigger that had focus", await t.active(), "mb-file")
  await t.press("ArrowDown")
  t.eq("ArrowDown opens the menu and focuses its first item", [await t.count("#mb-file-menu"), await t.active()].join(" "), "1 mb-new")
  await t.press("ArrowRight")
  t.eq("ArrowRight in an open menu moves to the next menu, open", [await t.count("#mb-file-menu"), await t.count("#mb-edit-menu"), await t.active()].join(" "), "0 1 mb-undo")
  await t.press("ArrowDown")
  await t.press("ArrowRight")
  t.eq("on a submenu trigger, ArrowRight opens the submenu instead", [await t.count("#mb-find-menu"), await t.active()].join(" "), "1 mb-next")
  await t.press("ArrowRight")
  t.eq("in a submenu, ArrowRight moves to the next menu of the bar", [await t.count("#mb-edit-menu"), await t.count("#mb-view-menu"), await t.active()].join(" "), "0 1 mb-zoom")
  await t.press("ArrowLeft")
  t.eq("ArrowLeft moves back", [await t.count("#mb-view-menu"), await t.count("#mb-edit-menu")].join(" "), "0 1")
  await t.press("Escape")
  t.eq("Escape closes it and focuses its trigger", [await t.count("#mb-edit-menu"), await t.active()].join(" "), "0 mb-edit")
  await page.click("#mb-file")
  t.eq("a click opens a menu", await t.count("#mb-file-menu"), 1)
  await page.hover("#mb-view")
  await t.settle(400)
  t.eq("while one is open, hovering another trigger opens that one", [await t.count("#mb-file-menu"), await t.count("#mb-view-menu")].join(" "), "0 1")
  await page.click("#mb-zoom")
  await t.settle()
  t.eq("an item runs and the menu closes", [await t.text("#mb-last"), await t.count("#mb-view-menu")].join(" "), "zoom 0")
  await page.hover("#mb-file")
  await t.settle(400)
  t.eq("with every menu closed, hovering opens nothing", await t.count("#mb-file-menu"), 0)
  await page.click("#mb-edit")
  await page.click("#mb-before")
  await t.settle()
  t.eq("an outside press closes it", await t.count("#mb-edit-menu"), 0)
}
