export default async function timeInput(t) {
  const { page } = t
  const seg = (root, type) => `#${root} input[data-type=${type}]`
  const values = (root) => page.locator(`#${root} input[role=spinbutton]`).evaluateAll((els) => els.map((el) => el.value).join("|"))
  const hidden = (root) => page.locator(`#${root} input[type=hidden]`).inputValue()
  t.eq("a group of spinbuttons: hour, minute and AM/PM in a 12-hour locale", [await t.attr("#ti", "role"), await t.attrs("#ti input[role=spinbutton]", "data-type"), await t.attr(seg("ti", "hour"), "aria-valuemax")].join(" "), "group hour,minute,dayPeriod 12")
  await page.click(seg("ti", "hour"))
  await page.keyboard.type("9")
  t.eq("a digit that can't start a second one fills the hour and moves on", [await values("ti"), await page.evaluate(() => document.activeElement.getAttribute("data-type"))].join(" "), "09|| minute")
  await page.keyboard.type("45")
  await page.keyboard.type("p")
  t.eq("typing fills the minute, and a letter the day period", [await values("ti"), await hidden("ti")].join(" "), "09|45|PM 21:45")
  t.eq("a time after max is invalid", (await t.attr("#ti", "data-invalid")) !== null, true)
  await page.click(seg("ti", "dayPeriod"))
  await t.press("ArrowUp")
  t.eq("ArrowUp on the day period toggles it", [await values("ti"), await hidden("ti")].join(" "), "09|45|AM 09:45")
  t.eq("a time in range is valid", await t.attr("#ti", "data-invalid"), null)
  await page.click(seg("ti", "minute"))
  await t.press("ArrowDown")
  t.eq("ArrowDown steps the minute", await values("ti"), "09|44|AM")
  await page.click("#ti-form-submit")
  t.eq("it submits with the form under its name", await t.text("#ti-form-sent"), "alarm=09:44")
  await page.click("#ti-form-reset")
  await t.settle()
  t.eq("a form reset empties it", [await values("ti"), await hidden("ti")].join(" "), "|| ")

  t.eq("a 24-hour locale with seconds has no day period", [await t.attrs("#cti input[role=spinbutton]", "data-type"), await t.attr(seg("cti", "hour"), "aria-valuemax")].join(" "), "hour,minute,second 23")
  await page.click(seg("cti", "second"))
  await page.keyboard.type("07")
  t.eq("controlled: a change reaches the app", [await t.text("#cti-value"), await values("cti")].join(" "), "09:30:07 09|30|07")
  await page.click("#cti-set")
  t.eq("controlled: the app's value shows in the segments", [await values("cti"), await hidden("cti")].join(" "), "23|05|10 23:05:10")
  await page.click(seg("cti", "hour"))
  await t.press("ArrowUp")
  t.eq("ArrowUp wraps the hour", await values("cti"), "00|05|10")
}
