export default async function carouselChecks(t) {
  const items = "#cr [data-slot=carousel-item]"
  t.eq("a named carousel region", (await t.attr("#cr", "role")) + " " + (await t.attr("#cr", "aria-roledescription")) + " " + (await t.attr("#cr", "aria-label")), "region carousel Colors")
  t.eq("slides are groups labelled by position", (await t.attrs(items, "role")) + " " + (await t.attrs(items, "aria-label")), "group,group,group,group 1 of 4,2 of 4,3 of 4,4 of 4")
  t.eq("slides out of view are hidden", await t.attrs(items, "aria-hidden"), ",true,true,true")
  t.eq("previous is aria-disabled on the first page, and stays focusable", (await t.attr("#cr-prev", "aria-disabled")) + " " + (await t.attr("#cr-prev", "disabled")), "true null")
  t.eq("indicators are a tablist of tabs, the first selected", (await t.attr("#cr-dots", "role")) + " " + (await t.attrs("#cr-dots [role=tab]", "aria-selected")), "tablist true,false,false,false")
  await t.page.click("#cr-next")
  await t.settle(500)
  t.eq("next reaches the app and moves the slides", (await t.text("#cr-page")) + " " + (await t.attrs(items, "aria-hidden")), "2 true,,true,true")
  await t.page.locator("#cr-dots [role=tab]").nth(3).click()
  await t.settle(500)
  t.eq("an indicator goes to its page", (await t.text("#cr-page")) + " " + (await t.attrs("#cr-dots [role=tab]", "aria-selected")), "4 false,false,false,true")
  t.eq("next is aria-disabled on the last page", await t.attr("#cr-next", "aria-disabled"), "true")
  await t.page.focus("#cr-dots [role=tab][aria-selected=true]")
  await t.press("ArrowLeft")
  await t.settle(500)
  t.eq("ArrowLeft in the indicators goes to the page before", await t.text("#cr-page"), "3")
  await t.page.click("#outside-next")
  await t.settle(500)
  t.eq("a Next outside connects through the controller", await t.text("#cr-page"), "4")
  t.eq("the play toggle's children are a function of its state", await t.text("#cr-play"), "Play")
  await t.page.click("#cr-play")
  t.eq("it starts rotation, and live updates turn off", (await t.text("#cr-play")) + " " + (await t.attr("#cr-viewport", "aria-live") ?? (await t.attr("#cr-content", "aria-live"))), "Stop off")
}
