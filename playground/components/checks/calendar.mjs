export default async function calendar(t) {
  const { page } = t
  const day = (root, date) => `#${root} [data-value="${date}"]`
  const focused = () => page.evaluate(() => document.activeElement?.getAttribute("data-value") ?? document.activeElement?.id)
  const heading = (root) => t.text(`#${root} [data-slot=calendar-heading]`)
  t.eq("a grid of the month, named, with weekday headers", [await t.attr("#cal table", "role"), await t.attr("#cal table", "aria-label"), await t.count("#cal [role=columnheader]"), await t.attr("#cal [role=columnheader]", "aria-label")].join(" "), "grid March 2026 7 Sunday")
  t.eq("one tab stop, on the selected day", await t.attrs("#cal [tabindex='0']", "data-value"), "2026-03-15")
  t.eq("the selected day and today are marked", [await t.attr(day("cal", "2026-03-15"), "aria-selected"), await t.attr(day("cal", "2026-03-10"), "aria-current")].join(" "), "true date")
  t.eq("an unavailable day is disabled", await t.attr(day("cal", "2026-03-20"), "aria-disabled"), "true")
  await page.locator(day("cal", "2026-03-15")).focus()
  await t.press("ArrowRight")
  t.eq("ArrowRight moves a day", await focused(), "2026-03-16")
  await t.press("ArrowDown")
  t.eq("ArrowDown moves a week", await focused(), "2026-03-23")
  await t.press("ArrowLeft")
  await t.press("ArrowUp")
  t.eq("ArrowLeft and ArrowUp move back", await focused(), "2026-03-15")
  await t.press("End")
  t.eq("End moves to the end of the week", await focused(), "2026-03-21")
  await t.press("Home")
  t.eq("Home moves to its start", await focused(), "2026-03-15")
  await t.press("Enter")
  t.eq("Enter selects the focused day, and the app hears it", await t.text("#cal-value"), '"2026-03-15"')
  await t.press("ArrowRight")
  await t.press("Space")
  t.eq("Space selects too", [await t.text("#cal-value"), await t.attr(day("cal", "2026-03-16"), "aria-selected"), await t.attr(day("cal", "2026-03-15"), "aria-selected")].join(" "), '"2026-03-16" true false')
  await page.click(day("cal", "2026-03-20"), { force: true })
  t.eq("an unavailable day can't be chosen", await t.text("#cal-value"), '"2026-03-16"')
  await page.locator(day("cal", "2026-03-16")).focus()
  await t.press("PageDown")
  t.eq("PageDown shows the next month, keeping the day", [await heading("cal"), await focused()].join(" "), "April 2026 2026-04-16")
  await t.press("PageDown")
  t.eq("not past max", await heading("cal"), "April 2026")
  t.eq("Next is disabled at max", await page.locator("#cal [data-slot=calendar-next]").evaluate((el) => el.disabled || el.getAttribute("aria-disabled") === "true"), true)
  await t.press("ArrowDown")
  t.eq("arrow keys stop at max", await focused(), "2026-04-20")
  t.eq("days after max are disabled", await t.attr(day("cal", "2026-04-21"), "aria-disabled"), "true")
  await page.click("#cal [data-slot=calendar-previous]")
  await page.click("#cal [data-slot=calendar-previous]")
  t.eq("Previous shows the month before", await heading("cal"), "February 2026")
  t.eq("days before min are disabled", [await t.attr(day("cal", "2026-02-09"), "aria-disabled"), String(await t.attr(day("cal", "2026-02-10"), "aria-disabled"))].join(" "), "true null")

  t.eq("two months, with the app's grids and days", [await heading("rcal"), await t.count("#rcal table"), await t.attr("#rcal-grid-1", "aria-label"), await t.count("#rcal-grid-1 .custom-day") > 27].join(" "), "June – July 2026 2 July 2026 true")
  await page.click(day("rcal", "2026-06-28"))
  await page.click(day("rcal", "2026-07-03"))
  t.eq("a range is chosen across the months", await t.text("#rcal-value"), '["2026-06-28","2026-07-03"]')
  t.eq("the days in it are marked", [await t.attr(day("rcal", "2026-07-01"), "aria-selected"), await t.attr(day("rcal", "2026-07-01"), "data-range-middle")].join(" "), "true ")
  await page.click("#rcal-next")
  t.eq("Next pages both months", await heading("rcal"), "July – August 2026")

  await page.selectOption("#scal-month", "4")
  t.eq("the month select turns the month", await heading("scal"), "April 2026")
  await page.selectOption("#scal-year", "2028")
  t.eq("the year select turns the year", await heading("scal"), "April 2028")
  t.eq("the years run from min to max", await page.locator("#scal-year option").evaluateAll((els) => els.map((el) => el.value).join(",")), "2024,2025,2026,2027,2028")
}
