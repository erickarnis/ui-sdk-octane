export default async function navigationMenu(t) {
  const { page } = t
  t.eq("a nav landmark with a list of items", [await page.locator("#nm").evaluate((el) => el.tagName), await t.attr("#nm", "aria-label"), await page.locator("#nm-list").evaluate((el) => el.tagName), await t.count("#nm-list > li")].join(" "), "NAV Main UL 3")
  t.eq("triggers are closed buttons", [await t.attr("#nm-products", "aria-expanded"), await t.attr("#nm-learn", "aria-expanded")].join(" "), "false false")
  t.eq("the current link is marked", await t.attr("#nm-blog", "aria-current"), "page")
  t.eq("closed content is not in the page, and the viewport is not shown", [await t.count("#nm-products-content"), await page.locator("#nm-viewport").evaluate((el) => el.matches(":popover-open"))].join(" "), "0 false")
  await page.click("#nm-products")
  t.eq("a press opens its content inside the viewport", [await t.attr("#nm-products", "aria-expanded"), await t.attr("#nm-products", "aria-controls"), await page.locator("#nm-viewport > #nm-products-content").count()].join(" "), "true nm-products-content 1")
  t.eq("the viewport is in the top layer, and takes the content's size", [await page.locator("#nm-viewport").evaluate((el) => el.matches(":popover-open")), (await t.attr("#nm-viewport", "style")).includes("--viewport-width")].join(" "), "true true")
  t.eq("the indicator follows the open trigger", await t.attr("#nm-indicator", "data-open"), "")
  await page.click("#nm-products")
  t.eq("a second press closes it", await t.count("#nm-products-content"), 0)

  await page.hover("#nm-learn")
  await t.settle(300)
  t.eq("resting the pointer on a trigger opens its content", [await t.count("#nm-learn-content"), await t.attr("#nm-learn", "aria-expanded")].join(" "), "1 true")
  await page.hover("#nm-products")
  await t.settle(300)
  t.eq("moving to another trigger switches the content in the one viewport", [await t.count("#nm-learn-content"), await page.locator("#nm-viewport > #nm-products-content").count(), await t.count("#nm-viewport")].join(" "), "0 1 1")
  await page.hover("#nm-editor")
  await t.settle(300)
  t.eq("the pointer can move into the content", await t.count("#nm-products-content"), 1)
  await page.mouse.move(900, 600)
  await t.settle(400)
  t.eq("leaving closes it after the close delay", await t.count("#nm-products-content"), 0)

  await page.locator("#nm-before").focus()
  await t.press("Tab")
  t.eq("each trigger is a tab stop", await t.active(), "nm-products")
  await t.press("Enter")
  await t.press("Tab")
  t.eq("Tab from an open trigger moves into its content", await t.active(), "nm-editor")
  await t.press("Tab")
  await t.press("Tab")
  t.eq("Tab from the end of the content moves to the next trigger, and the content stays open while focus is in the menu", [await t.active(), await t.count("#nm-products-content")].join(" "), "nm-learn 1")
  await page.locator("#nm-viewer").focus()
  await t.press("Escape")
  t.eq("Escape closes it and returns focus to its trigger", [await t.count("#nm-products-content"), await t.active()].join(" "), "0 nm-products")
  await t.press("ArrowRight")
  t.eq("ArrowRight moves between the triggers", await t.active(), "nm-learn")
  await t.press("End")
  t.eq("End moves to the last item", await t.active(), "nm-blog")
  await t.press("Home")
  t.eq("Home moves to the first", await t.active(), "nm-products")
  await t.press("Enter")
  await page.click("#nm-editor")
  await t.settle()
  t.eq("following a link closes the menu", await t.count("#nm-products-content"), 0)
  await page.click("#nm-learn")
  await page.click("#nm-before")
  await t.settle(200)
  t.eq("an outside press closes it", await t.count("#nm-learn-content"), 0)

  await page.click("#cnm-trigger")
  t.eq("controlled: a press reaches the app, and without a viewport the content is its own popup", [await t.text("#cnm-value"), await t.count("#cnm-content"), await page.locator("#cnm-content").evaluate((el) => el.matches(":popover-open"))].join(" "), "more 1 true")
  await t.press("Escape")
  t.eq("controlled: Escape asks the app to close", [await t.text("#cnm-value"), await t.count("#cnm-content")].join(" "), "null 0")
  await page.click("#cnm-outside")
  t.eq("controlled: the app opens it", [await t.count("#cnm-content"), await t.attr("#cnm-trigger", "aria-expanded")].join(" "), "1 true")
}
