export default async function toast(t) {
  const { page } = t
  const toasts = (region) => page.locator(`#${region} [data-slot=toast]`).count()
  t.eq("the region starts empty", await t.count("#t-region [data-slot=toast]"), 0)
  await page.click("#t-plain")
  t.eq("toast() shows a toast in a named region in the top layer", [await toasts("t-region"), await t.attr("#t-region", "role"), await t.attr("#t-region", "aria-label"), await page.locator("#t-region").evaluate((el) => el.matches(":popover-open"))].join(" "), "1 region Notifications true")
  t.eq("a string renders as its title, which names the toast", await page.locator("#t-region [data-slot=toast]").evaluate((el) => document.getElementById(el.getAttribute("aria-labelledby")).textContent), "Saved")
  await t.settle(1200)
  t.eq("it leaves after its duration", await t.count("#t-region [data-slot=toast]"), 0)

  await page.click("#t-rich")
  t.eq("title, description, action and cancel render from data, the title as a node", [await t.count("#t-rich-title"), await t.text("#t-region [data-slot=toast-description]"), await t.text("#t-region [data-slot=toast-action]"), await t.text("#t-region [data-slot=toast-close]")].join("|"), "1|It's in the bin.|Undo|Dismiss")
  t.eq("described by its description", await page.locator("#t-region [data-slot=toast]").evaluate((el) => document.getElementById(el.getAttribute("aria-describedby")).textContent), "It's in the bin.")
  await page.click("#t-region [data-slot=toast-action]")
  await t.settle(600)
  t.eq("the action runs and dismisses it", [await t.text("#t-log"), await t.count("#t-region [data-slot=toast]")].join(" "), "undo+dismiss:action 0")
  await page.click("#t-rich")
  await page.click("#t-region [data-slot=toast-close]")
  await t.settle(600)
  t.eq("the cancel button runs and closes it", [await t.text("#t-log"), await t.count("#t-region [data-slot=toast]")].join(" "), "cancel+dismiss:close-press 0")
  await page.click("#t-rich")
  await page.locator("#t-plain").focus()
  await t.press("F6")
  t.eq("F6 moves focus to the region's toasts", await page.evaluate(() => document.activeElement?.getAttribute("data-slot")), "toast")
  await t.press("Escape")
  await t.settle(600)
  t.eq("Escape on a toast dismisses it", [await t.count("#t-region [data-slot=toast]"), (await t.text("#t-log")).endsWith("dismiss:escape-key")].join(" "), "0 true")

  await page.click("#t-second")
  t.eq("a second toaster shows in its own region, rendered by the app's parts", [await t.count("#t2-custom"), await t.attr("#t-region2", "data-side"), await t.text("#t2-title"), await t.attr("#t2-custom", "aria-labelledby"), await t.attr("#t2-custom", "aria-describedby"), await t.count("#t-region [data-slot=toast]")].join(" "), "1 top Custom t2-title t2-description 0")
  await page.click("#t2-action")
  await t.settle(600)
  t.eq("the app's action part runs its handler and dismisses", [await t.text("#t-log"), await t.count("#t2-custom")].join(" "), "custom-action 0")
}
