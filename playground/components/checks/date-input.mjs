export default async function dateInput(t) {
  const { page } = t
  const seg = (root, type) => `#${root} input[data-type=${type}]`
  const values = (root) => page.locator(`#${root} input[role=spinbutton]`).evaluateAll((els) => els.map((el) => el.value).join("/"))
  t.eq("a group named by its field's label, with spinbutton segments in the locale's order", [await t.attr("#di", "role"), await t.attr("#di", "aria-labelledby"), await t.attrs("#di input[role=spinbutton]", "data-type")].join(" "), "group di-label month,day,year")
  t.eq("each segment is named by its unit, and empty", [await t.attr(seg("di", "month"), "aria-label"), await t.attr(seg("di", "month"), "aria-valuetext")].join(" "), "month Empty")
  t.eq("the literal between them is hidden", await t.attrs("#di span[data-type=literal]", "aria-hidden"), "true,true")
  await page.click(seg("di", "month"))
  await page.keyboard.type("3")
  t.eq("a digit that can't start a second one fills the segment and moves on", await values("di"), "03//")
  t.eq("focus moved to the day", await page.evaluate(() => document.activeElement.getAttribute("data-type")), "day")
  await page.keyboard.type("15")
  await page.keyboard.type("2026")
  t.eq("typing fills every segment, and the hidden input holds the ISO date", [await values("di"), await page.locator("#di input[type=hidden]").inputValue()].join(" "), "03/15/2026 2026-03-15")
  await page.click("#di-form-submit")
  t.eq("it submits with the form under its name", await t.text("#di-form-sent"), "start=2026-03-15")
  await page.click(seg("di", "day"))
  await t.press("ArrowUp")
  t.eq("ArrowUp steps the segment", await values("di"), "03/16/2026")
  await t.press("ArrowDown")
  await t.press("ArrowDown")
  t.eq("ArrowDown steps it back", await values("di"), "03/14/2026")
  await t.press("ArrowLeft")
  t.eq("ArrowLeft moves to the segment before", await page.evaluate(() => document.activeElement.getAttribute("data-type")), "month")
  await t.press("ArrowRight")
  await t.press("ArrowRight")
  t.eq("ArrowRight moves to the next", await page.evaluate(() => document.activeElement.getAttribute("data-type")), "year")
  await page.click(seg("di", "month"))
  await page.keyboard.type("01")
  await page.keyboard.type("05")
  t.eq("a date before min is invalid", [await values("di"), (await t.attr("#di", "data-invalid")) !== null].join(" "), "01/05/2026 true")
  await page.click(seg("di", "month"))
  await page.keyboard.type("06")
  t.eq("a date within range is valid", (await t.attr("#di", "data-invalid")) === null, true)
  await page.click(seg("di", "day"))
  await t.press("Backspace")
  await t.press("Backspace")
  t.eq("Backspace clears a segment, which empties the value", [await t.attr(seg("di", "day"), "aria-valuetext"), await page.locator("#di input[type=hidden]").inputValue()].join(" "), "Empty ")
  await page.click("#di-form-reset")
  await t.settle()
  t.eq("a form reset empties it", await values("di"), "//")

  await page.click(seg("cdi", "year"))
  await t.press("ArrowUp")
  t.eq("controlled: a change reaches the app", [await t.text("#cdi-value"), await values("cdi")].join(" "), "2027-03-15 03/15/2027")
  await page.click("#cdi-set")
  t.eq("controlled: the app's value shows in the segments", [await values("cdi"), await page.locator("#cdi input[type=hidden]").inputValue()].join(" "), "07/04/2027 2027-07-04")

  t.eq("a function of state renders the app's segments, in the locale's order and names", [await t.attrs("#xdi [data-slot=date-input-segment]", "class"), await t.attr("#xdi .seg-day", "aria-label"), await values("xdi")].join(" "), "seg-day,seg-literal,seg-month,seg-literal,seg-year Tag 01/05/2026")
}
