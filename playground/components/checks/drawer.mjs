export default async function drawer(t) {
  const { page } = t
  const open = (selector) => page.locator(selector).count()
  t.eq("closed at first", await open("#dr"), 0)
  await page.click("#dr-trigger")
  await t.settle(400)
  t.eq("a modal dialog, named and described", [await t.attr("#dr", "role"), await t.attr("#dr", "aria-modal"), await t.attr("#dr", "aria-labelledby"), await t.attr("#dr", "aria-describedby")].join(" "), "dialog true dr-title dr-description")
  t.eq("in a viewport in the top layer, on its side", [await page.locator("[data-slot=drawer-viewport]").evaluate((el) => el.matches(":popover-open")), await t.attr("#dr", "data-side")].join(" "), "true bottom")
  t.eq("rests on its first snap point", await t.attr("#dr", "data-snap-point"), "0.25")
  t.eq("the page behind is inert", await t.attr("#cdr-trigger", "inert"), "")
  t.eq("focus moves inside", await t.active(), "dr-handle")
  await t.press("Enter")
  await t.settle(500)
  t.eq("pressing the handle moves to the next snap point", [await t.attr("#dr", "data-snap-point"), await t.text("#dr-snap")].join(" "), "1 1")
  await t.press("ArrowDown")
  await t.settle(500)
  t.eq("an arrow key on the handle steps back", await t.attr("#dr", "data-snap-point"), "0.25")
  await page.locator("#dr-close").focus()
  await t.press("Tab")
  t.eq("Tab stays inside", await t.active(), "dr-handle")
  await t.press("Escape")
  await t.settle(600)
  t.eq("Escape closes it and returns focus to the trigger", [await open("#dr"), await t.active()].join(" "), "0 dr-trigger")
  await page.click("#dr-trigger")
  await t.settle(400)
  await page.mouse.click(600, 20)
  await t.settle(600)
  t.eq("a press on the backdrop closes it", await open("#dr"), 0)
  await page.click("#dr-trigger")
  await t.settle(400)
  const box = await page.locator("#dr-handle").boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + 2)
  await page.mouse.down()
  for (let step = 1; step <= 10; step++) await page.mouse.move(box.x + box.width / 2, box.y + 2 + step * 25, { steps: 2 })
  await page.mouse.up()
  await t.settle(800)
  t.eq("a swipe down from the lowest snap point closes it", await open("#dr"), 0)

  await page.click("#cdr-trigger")
  await t.settle(400)
  t.eq("controlled: the trigger asks the app, and it opens from the end, the right in this writing direction", [await t.text("#cdr-open"), await open("#cdr"), await t.attr("#cdr", "data-side")].join(" "), "true 1 right")
  await page.click("#cdr-close")
  await t.settle(600)
  t.eq("controlled: a close asks the app to close", [await t.text("#cdr-open"), await open("#cdr")].join(" "), "false 0")

  t.eq("an outlet is closed while its drawer is", await t.attr("#dr-outlet", "data-closed"), "")
  await page.click("#rdr-trigger")
  await t.settle(400)
  t.eq("a trigger outside the drawer opens it through the controller, and the outlet follows", [await open("#rdr"), await t.attr("#dr-outlet", "data-open")].join(" "), "1 ")
  await page.click("#rdr-close")
  await t.settle(600)
  t.eq("and focus comes back to it", [await open("#rdr"), await t.active()].join(" "), "0 rdr-trigger")
}
