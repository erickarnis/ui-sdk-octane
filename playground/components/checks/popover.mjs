export default async function popover(t) {
  const { page } = t
  t.eq("trigger reflects the closed state", [await t.attr("#pop-trigger", "aria-haspopup"), await t.attr("#pop-trigger", "aria-expanded")].join(" "), "dialog false")
  t.eq("closed content is not in the page", await t.count("#pop"), 0)
  await page.locator("#pop-trigger").focus()
  await t.press("Enter")
  t.eq("Enter opens it", [await t.count("#pop"), await t.attr("#pop-trigger", "aria-expanded"), await t.attr("#pop-trigger", "aria-controls")].join(" "), "1 true pop")
  t.eq("named by its title and described by its description", [await t.attr("#pop", "role"), await t.attr("#pop", "aria-labelledby"), await t.attr("#pop", "aria-describedby")].join(" "), "dialog pop-title pop-description")
  t.eq("in the top layer", await page.locator("#pop").evaluate((el) => el.matches(":popover-open")), true)
  t.eq("opening moves focus to the first focusable element", await t.active(), "pop-input")
  const boxes = await page.evaluate(() => {
    const trigger = document.getElementById("pop-trigger").getBoundingClientRect()
    const content = document.getElementById("pop").getBoundingClientRect()
    return { below: Math.round(content.top - trigger.bottom), left: Math.round(content.left - trigger.left) }
  })
  t.eq("positioned below its trigger, at its start, by the side offset", JSON.stringify(boxes), JSON.stringify({ below: 4, left: 0 }))
  t.eq("the arrow carries the side", await t.attr("#pop-arrow", "data-side"), "bottom")
  await page.keyboard.press("Shift+Tab")
  t.eq("Shift+Tab from the first element returns focus to the trigger", await t.active(), "pop-trigger")
  await t.press("Tab")
  await t.press("Tab")
  await t.press("Tab")
  t.eq("Tab moves through the popover in order", await t.active(), "pop-close")
  await t.press("Tab")
  await t.settle()
  t.eq("Tab from the last element moves to the element after the trigger, and closes", (await t.active()) + " " + (await t.count("#pop")), "pop-after 0")
  await page.click("#pop-trigger")
  await page.click("#pop-apply")
  t.eq("pressing a button inside keeps it open", await t.count("#pop"), 1)
  await t.press("Escape")
  t.eq("Escape closes it and returns focus to the trigger", (await t.count("#pop")) + " " + (await t.active()), "0 pop-trigger")
  await t.press("Space")
  t.eq("Space opens it", await t.count("#pop"), 1)
  await page.click("#pop-close")
  t.eq("the close button closes it and returns focus", (await t.count("#pop")) + " " + (await t.active()), "0 pop-trigger")
  await page.click("#pop-trigger")
  await page.click("#pop-trigger")
  t.eq("a click on the open trigger closes it", await t.count("#pop"), 0)
  await page.click("#pop-trigger")
  await page.click("#pop-after")
  t.eq("clicking outside closes it, and the press reaches what it hits", (await t.count("#pop")) + " " + (await t.active()), "0 pop-after")

  await page.click("#cpop-trigger")
  t.eq("controlled: press reaches the app and opens", [await t.text("#cpop-open"), await t.count("#cpop"), await t.text("#cpop-trigger")].join(" "), "true 1 Hide")
  t.eq("with initial focus none, focus stays on the trigger", await t.active(), "cpop-trigger")
  await page.click("#cpop-inside")
  await t.settle()
  t.eq("controlled: the app's change closes it", (await t.text("#cpop-open")) + " " + (await t.count("#cpop")), "false 0")
  await page.click("#cpop-outside")
  t.eq("controlled: the app opens it from outside", (await t.count("#cpop")) + " " + (await t.attr("#cpop-trigger", "aria-expanded")), "1 true")
  await t.press("Escape")

  await page.click("#rpop-trigger")
  t.eq("a trigger outside the popover opens it through the controller", (await t.count("#rpop")) + " " + (await t.attr("#rpop-trigger", "aria-expanded")), "1 true")
  await t.press("Escape")
  t.eq("and takes focus back", await t.active(), "rpop-trigger")

  await page.click("#outer-trigger")
  await page.click("#inner-trigger")
  t.eq("using a nested popover keeps both open", (await t.count("#outer")) + " " + (await t.count("#inner")), "1 1")
  await t.press("Escape")
  t.eq("Escape closes only the nested one and returns focus to its trigger", [await t.count("#outer"), await t.count("#inner"), await t.active()].join(" "), "1 0 inner-trigger")
  await page.click("#inner-trigger")
  await page.click("#pop-after")
  t.eq("clicking outside closes every popover", (await t.count("#outer")) + " " + (await t.count("#inner")), "0 0")

  await page.click("#ppop-trigger")
  t.eq("with a container, the content renders into it", await page.locator("#portal-root > #ppop").count(), 1)
  await page.click("#ppop-inner-trigger")
  t.eq("a popover inside it renders into the same container", await page.locator("#portal-root #ppop-inner").count(), 1)
  await page.click("#ppop-inner-close")
  t.eq("closing the inner one keeps the outer", (await t.count("#ppop")) + " " + (await t.active()), "1 ppop-inner-trigger")
  await t.press("Escape")
  t.eq("Escape closes the outer and returns focus", (await page.locator("#portal-root > *").count()) + " " + (await t.active()), "0 ppop-trigger")
}
