export default async function radio(t) {
  const radios = "#rg [role=radio]"
  t.eq("a radiogroup with its name", (await t.attr("#rg", "role")) + " " + (await t.attr("#rg", "aria-label")), "radiogroup Size")
  t.eq("nothing checked at first", await t.attrs(radios, "aria-checked"), "false,false,false,false")
  await t.page.locator("#rg-form-submit").focus()
  await t.page.keyboard.press("Shift+Tab")
  t.eq("Tab lands on the first radio when none is checked", await t.active(), "rg-small")
  await t.press("Space")
  t.eq("Space checks the focused radio", await t.attrs(radios, "aria-checked"), "true,false,false,false")
  await t.press("ArrowDown")
  t.eq("ArrowDown moves to the next and checks it", (await t.attrs(radios, "aria-checked")) + " " + (await t.active()), "false,true,false,false rg-medium")
  await t.press("ArrowRight")
  t.eq("arrows skip the disabled radio", (await t.attrs(radios, "aria-checked")) + " " + (await t.active()), "false,false,false,true rg-huge")
  await t.press("ArrowRight")
  t.eq("arrows wrap", await t.active(), "rg-small")
  await t.press("ArrowUp")
  t.eq("ArrowUp wraps back", await t.active(), "rg-huge")
  t.eq("one tab stop, on the checked radio", await t.attrs(radios, "tabindex"), "-1,-1,,0")
  await t.press("Tab")
  t.eq("Tab leaves the group after one stop", await t.active(), "rg-form-submit")
  await t.page.click("#rg-large", { force: true })
  t.eq("clicking a disabled radio does nothing", await t.attrs(radios, "aria-checked"), "false,false,false,true")
  await t.page.click("#rg-medium")
  t.eq("click checks and unchecks the others", await t.attrs(radios, "aria-checked"), "false,true,false,false")
  t.eq("the indicator shows in the checked radio only", await t.count("#rg [data-slot=radio-indicator]"), 1)
  await t.page.click("#rg-form-submit")
  t.eq("the form submits the checked value", await t.text("#rg-form-sent"), "size=medium")
  await t.page.locator("#rg-medium").focus()
  await t.press("Enter")
  t.eq("Enter never checks", await t.attrs(radios, "aria-checked"), "false,true,false,false")
  await t.page.click("#rg-form-reset")
  await t.settle()
  t.eq("a form reset returns to nothing checked", await t.attrs(radios, "aria-checked"), "false,false,false,false")

  const controlled = "#crg [role=radio]"
  t.eq("controlled: starts from the app's value", await t.attrs(controlled, "aria-checked"), "false,true,false,false")
  await t.page.click("#crg-small")
  t.eq("controlled: press reaches the app", (await t.text("#crg-value")) + " " + (await t.attrs(controlled, "aria-checked")), "small true,false,false,false")
  await t.page.click("#crg-set")
  t.eq("controlled: a value from outside checks its radio and moves the tab stop", (await t.attrs(controlled, "aria-checked")) + " " + (await t.attrs(controlled, "tabindex")), "false,false,false,true -1,-1,-1,0")

  t.eq("in a field: the field's label names the group", await t.attr("#frg", "aria-labelledby"), "frg-label")
  t.eq("in a field: radios take the field's name", await t.attrs("#field input[type=radio]", "name"), "plan,plan")
}
