export default async function overlays(t) {
  const { page } = t
  await page.click("#o-toast")
  t.eq("the host renders a region for toast(), with the props it was given", [await t.count("#o-region [data-slot=toast]"), await t.attr("#o-region", "data-side"), await t.text("#o-region [data-slot=toast-title]")].join(" "), "1 top Hosted")
  await page.click("#o-confirm")
  await t.settle(200)
  const dialog = page.locator("[role=alertdialog]")
  t.eq("confirm() opens an alert dialog from its options", [await dialog.count(), await t.text("[role=alertdialog] [data-slot=alert-dialog-title], [role=alertdialog] h2"), await t.text("[role=alertdialog] p")].join("|"), "1|Delete it?|This can't be undone.")
  t.eq("named and described by them", await dialog.evaluate((el) => [document.getElementById(el.getAttribute("aria-labelledby"))?.textContent, document.getElementById(el.getAttribute("aria-describedby"))?.textContent].join("|")), "Delete it?|This can't be undone.")
  t.eq("with Cancel and the confirm label, focus on the first", [await page.locator("[role=alertdialog] button").allTextContents().then((all) => all.join(",")), await t.active()].join(" "), "Cancel,Delete Cancel")
  await page.locator("[role=alertdialog] button", { hasText: "Delete" }).click()
  await t.settle(400)
  t.eq("confirming resolves true and the dialog goes", [await t.text("#o-answer"), await dialog.count()].join(" "), "true 0")
  t.eq("focus returns to what opened it", await t.active(), "o-confirm")
  await page.click("#o-confirm")
  await t.settle(200)
  await t.press("Escape")
  await t.settle(400)
  t.eq("Escape resolves false", [await t.text("#o-answer"), await dialog.count()].join(" "), "false 0")
  await page.click("#o-confirm")
  await t.settle(200)
  await page.locator("[role=alertdialog] button", { hasText: "Cancel" }).click()
  await t.settle(400)
  t.eq("Cancel resolves false, and a second question opens again", [await t.text("#o-answer"), await dialog.count()].join(" "), "false 0")
}
