import { chromium } from "playwright"
const browser = await chromium.launch()
const page = await browser.newPage()
page.on("pageerror", (e) => console.log("pageerror: " + e.message))
page.on("console", (m) => console.log("console " + m.type() + ": " + m.text()))
await page.goto("http://127.0.0.1:4399/")
await page.waitForTimeout(600)
const labels = async () => page.evaluate(async () => (await window.agent.snapshot()).map((c) => c.ref + ":" + c.label + (c.offPage ? "(offPage)" : "")).join(" "))
console.log(await labels())
await page.click("#toggle-mount")
await page.waitForTimeout(1500)
console.log(await labels(), "| in page:", await page.locator("#mounted").count())
const acted = await page.evaluate(async () => JSON.stringify(await window.agent.act({ steps: [{ ref: "Sections", action: "setValue", args: ["b"] }, { ref: "c1", action: "toggle" }] })))
console.log("act:", acted.slice(0, 300))
console.log("tab b selected:", await page.locator("#tabs [role=tab]").nth(1).getAttribute("aria-selected"), "| c1 pressed:", await page.getAttribute("#mute", "aria-pressed"))
await browser.close()
