export default async function tabs(t) {
  const tab = "#tabs [role=tab]"
  const shown = () => t.page.locator("#tabs [role=tabpanel]").evaluateAll((els) => els.filter((el) => !el.hidden).map((el) => el.textContent).join("|"))
  t.eq("list is a tablist with its label", await t.attr("#tabs [role=tablist]", "aria-label"), "Sections")
  t.eq("first tab selected", await t.attrs(tab, "aria-selected"), "true,false,false,false")
  t.eq("one tab stop", await t.attrs(tab, "tabindex"), "0,-1,-1,-1")
  t.eq("its panel shows", await shown(), "Panel A")
  const controls = await t.page.locator(tab).nth(0).getAttribute("aria-controls")
  t.eq("tab controls a panel labelled by it", await t.attr(`[id="${controls}"]`, "aria-labelledby"), await t.page.locator(tab).nth(0).getAttribute("id"))
  t.eq("tab icon and indicator render", (await t.count("#tabs [data-slot=tabs-tab-icon]")) + (await t.count("#tabs [data-slot=tabs-indicator]")), 2)

  await t.page.locator(tab).nth(0).focus()
  await t.press("ArrowRight")
  t.eq("ArrowRight selects the next tab", await t.attrs(tab, "aria-selected"), "false,true,false,false")
  t.eq("and shows its panel", await shown(), "Panel B")
  await t.press("ArrowRight")
  t.eq("a disabled tab takes focus but not the selection", (await t.attrs(tab, "aria-selected")) + " " + (await t.active()), "false,true,false,false " + (await t.page.locator(tab).nth(2).getAttribute("id")))
  await t.press("ArrowRight")
  t.eq("the next enabled tab is selected", await t.attrs(tab, "aria-selected"), "false,false,false,true")
  await t.press("ArrowRight")
  t.eq("focus loops to the first", await t.attrs(tab, "aria-selected"), "true,false,false,false")
  await t.press("End")
  t.eq("End selects the last", await shown(), "Panel D")
  await t.press("Home")
  t.eq("Home selects the first", await shown(), "Panel A")
  await t.page.locator(tab).nth(1).click()
  t.eq("click selects", await shown(), "Panel B")
  await t.press("Tab")
  t.eq("Tab moves into the panel", await t.active(), await t.page.locator(tab).nth(1).getAttribute("aria-controls"))

  const manual = "#ctabs [role=tab]"
  t.eq("vertical list says so", await t.attr("#ctabs [role=tablist]", "aria-orientation"), "vertical")
  t.eq("controlled: starts from the app's value", await t.attrs(manual, "aria-selected"), "false,true")
  await t.page.locator(manual).nth(1).focus()
  await t.press("ArrowUp")
  t.eq("manual: arrows move focus only", (await t.attrs(manual, "aria-selected")) + " " + (await t.active()), "false,true " + (await t.page.locator(manual).nth(0).getAttribute("id")))
  await t.press("Enter")
  t.eq("manual: Enter selects", await t.attrs(manual, "aria-selected"), "true,false")
  t.eq("the app heard it", await t.text("#ctabs-value"), "a")
}
