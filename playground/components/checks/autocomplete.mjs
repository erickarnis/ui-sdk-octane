export default async function autocomplete(t) {
  const { page } = t
  const shown = (list) => page.locator(list + " [role=option]:visible").allTextContents().then((all) => all.join(","))
  t.eq("the input is a combobox named by its label, with the default text", [await t.attr("#a-input", "role"), await t.attr("#a-input", "aria-labelledby"), await page.inputValue("#a-input")].join(" "), "combobox a-label Ber")
  await page.click("#a-input")
  await t.press("ArrowDown")
  t.eq("ArrowDown opens the suggestions for the text, focus in the input", [await t.visible("#a-content"), await shown("#a-list"), await t.active()].join(" "), "true Berlin,Bern a-input")
  t.eq("the matched text is marked", await page.locator("#a-Berlin mark").first().textContent(), "Ber")
  t.eq("nothing is highlighted yet", await t.attr("#a-input", "aria-activedescendant"), null)
  await t.press("ArrowDown")
  await t.press("ArrowDown")
  t.eq("arrows move the highlight", await t.attr("#a-input", "aria-activedescendant"), "a-Bern")
  await t.press("Enter")
  t.eq("Enter fills the text in and closes", (await page.inputValue("#a-input")) + " " + (await t.visible("#a-content")), "Bern false")
  await page.fill("#a-input", "")
  await page.keyboard.type("lo")
  await t.settle()
  t.eq("typing filters the suggestions", await shown("#a-list"), "London")
  await page.click("#a-London")
  t.eq("a click fills the text in", (await page.inputValue("#a-input")) + " " + (await t.visible("#a-content")), "London false")
  await page.click("#a-form-submit")
  t.eq("the text submits under the name", await t.text("#a-form-sent"), "city=London")
  await page.fill("#a-input", "")
  await page.keyboard.type("Oslo")
  await t.settle()
  t.eq("no match shows the empty part, and the text stays free", (await shown("#a-list")) + "|" + (await t.text("#a-empty")) + "|" + (await page.inputValue("#a-input")), "|No city|Oslo")
  await t.press("Escape")
  await page.click("#a-clear")
  t.eq("clear empties the field", await page.inputValue("#a-input"), "")

  await page.click("#d-input")
  await page.keyboard.type("par")
  await t.settle()
  t.eq("controlled: each keystroke reaches the app", await t.text("#d-value"), "par")
  const list = "#" + (await t.attr("#d-input", "aria-controls")).replaceAll(":", "\\:")
  t.eq("data: the items render filtered", await shown(list), "Paris")
  await t.press("Escape")
  await t.press("Escape")
  await t.press("Enter")
  t.eq("Enter with the list closed submits the text", await t.text("#d-submitted"), "par")
  await page.click("#d-set")
  t.eq("controlled: text set from outside reaches the input", await page.inputValue("#d-input"), "Paris")
}
