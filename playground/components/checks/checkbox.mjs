export default async function checkbox(t) {
  t.eq("renders a checkbox, unchecked", (await t.attr("#cb", "role")) + " " + (await t.attr("#cb", "aria-checked")), "checkbox false")
  t.eq("the indicator is absent while unchecked", await t.count("#cb-indicator"), 0)
  await t.page.click("#cb")
  t.eq("click checks it", await t.attr("#cb", "aria-checked"), "true")
  t.eq("the indicator shows while checked", await t.count("#cb-indicator"), 1)
  await t.press("Space")
  t.eq("Space unchecks it", await t.attr("#cb", "aria-checked"), "false")
  await t.press("Enter")
  t.eq("Enter submits and never toggles", (await t.attr("#cb", "aria-checked")) + " " + (await t.text("#cb-form-sent")), "false (empty)")
  await t.press("Space")
  await t.page.click("#cb-form-submit")
  t.eq("checked, it submits its name and value", await t.text("#cb-form-sent"), "terms=yes")
  await t.page.click("#cb-form-reset")
  await t.settle()
  t.eq("a form reset unchecks it", await t.attr("#cb", "aria-checked"), "false")

  t.eq("controlled: indeterminate is mixed", await t.attr("#ccb", "aria-checked"), "mixed")
  t.eq("the indicator reads the state", await t.text("#ccb"), "-")
  await t.page.click("#ccb")
  t.eq("controlled: press checks it through the app", (await t.attr("#ccb", "aria-checked")) + " " + (await t.text("#ccb-value")) + " " + (await t.text("#ccb")), "true true x")

  t.eq("the group is named by its label", (await t.attr("#cbg", "role")) + " " + (await t.attr("#cbg", "aria-labelledby")), "group toppings-label")
  t.eq("the group's value checks its boxes from the first render", await t.attrs("#cbg [role=checkbox]", "aria-checked"), "mixed,false,true,false")
  t.eq("the parent points at its children", await t.attr("#cbg-all", "aria-controls"), "cbg-cheese cbg-olives cbg-basil")
  await t.page.click("#cbg-cheese")
  t.eq("checking a box adds its value", await t.text("#cbg-value"), "cheese,olives")
  await t.page.click("#group-form-submit")
  t.eq("every checked value submits under the group's name", await t.text("#group-form-sent"), "topping=cheese&topping=olives")
  await t.page.click("#cbg-all")
  t.eq("the parent unchecks every enabled box", (await t.attrs("#cbg [role=checkbox]", "aria-checked")) + " " + (await t.text("#cbg-value")), "false,false,false,false ")
  await t.page.click("#cbg-all")
  t.eq("and checks them, leaving the disabled one", await t.text("#cbg-value"), "cheese,olives")
  await t.page.click("#cbg-set")
  t.eq("a value set from outside reaches the boxes and the parent", await t.attrs("#cbg [role=checkbox]", "aria-checked"), "mixed,true,false,true")
  await t.page.locator("#cbg-all").focus()
  await t.press("Tab")
  t.eq("Tab moves through the boxes in order", await t.active(), "cbg-cheese")

  t.eq("in a field: named by the label", (await t.attr("#fcb", "aria-labelledby")) + " " + (await t.attr("#fcb-label", "for")), "fcb-label fcb")
  await t.page.click("#fcb-label")
  t.eq("clicking its label toggles it once", await t.attr("#fcb", "aria-checked"), "true")
}
