export default async function alertDialog(t) {
  const { page } = t
  t.eq("trigger names a dialog popup", await t.attr("#ad-trigger", "aria-haspopup"), "dialog")
  await page.click("#ad-trigger")
  t.eq("opens as an alert dialog, named and described", [await t.attr("#ad", "role"), await t.attr("#ad", "aria-labelledby"), await t.attr("#ad", "aria-describedby")].join(" "), "alertdialog ad-title ad-description")
  t.eq("modal", await page.locator("#ad").evaluate((el) => el.matches(":modal") || el.getAttribute("aria-modal") === "true"), true)
  t.eq("focus moves inside, to its first button", await t.active(), "ad-cancel")
  await page.mouse.click(5, 5)
  await t.settle()
  t.eq("a press outside does not dismiss it", await t.count("#ad"), 1)
  await page.locator("#ad-cancel").focus()
  await t.press("Tab")
  await t.press("Tab")
  t.eq("Tab stays inside", await t.active(), "ad-cancel")
  await t.press("Escape")
  await t.settle()
  t.eq("Escape closes it and returns focus to the trigger", [await t.count("#ad"), await t.active(), await t.text("#ad-result")].join(" "), "0 ad-trigger escape-key")
  await t.press("Enter")
  await page.click("#ad-delete")
  await t.settle()
  t.eq("a close button closes it", [await t.count("#ad"), await t.active()].join(" "), "0 ad-trigger")

  await page.click("#cad-trigger")
  t.eq("controlled: the trigger asks the app to open", [await t.text("#cad-open"), await t.count("#cad")].join(" "), "true 1")
  await page.click("#cad-close")
  await t.settle()
  t.eq("controlled: a close asks the app to close", [await t.text("#cad-open"), await t.count("#cad")].join(" "), "false 0")

  await page.click("#q-ask")
  t.eq("confirm() opens the app's alert dialog through its controller", await t.count("#q"), 1)
  await page.click("#q-yes")
  await t.settle()
  t.eq("the agreeing close resolves true", [await t.text("#q-answer"), await t.count("#q")].join(" "), "true 0")
  await page.click("#q-ask")
  await t.press("Escape")
  await t.settle()
  t.eq("Escape resolves false", await t.text("#q-answer"), "false")
  await page.click("#q-ask")
  await page.click("#q-no")
  await t.settle()
  t.eq("another close resolves false", [await t.text("#q-answer"), await t.active()].join(" "), "false q-ask")
}
