export default async function tokenInput(t) {
  const { page } = t
  const tokens = (editor) => page.locator(editor + " [data-slot=token-input-host]").count()
  t.eq("the editor is a multiline textbox, named, with its placeholder", [await t.attr("#t-editor", "role"), await t.attr("#t-editor", "aria-multiline"), await t.attr("#t-editor", "aria-placeholder")].join(" "), "textbox true Ask")
  t.eq("tokens render renderToken's content in their hosts", (await page.locator("#t-editor [data-slot=token-input-token]").allTextContents()).join(","), "routes.tsx,app.tsx")
  t.eq("the hosts are atomic and read as their kind", (await t.attrs("#t-editor [data-slot=token-input-host]", "contenteditable")) + " " + (await t.text("#t-editor [data-slot=token-input-token-label]")), "false,false file")
  await page.click("#t-form-submit")
  t.eq("the text submits under the name, tokens in the codec's form", await t.text("#t-form-sent"), "prompt=Open [@routes.ts](file:routes.ts) and [@app.ts](file:app.ts)")
  await page.click("#t-editor")
  await t.press("Control+End")
  await t.press("End")
  await page.keyboard.type(" now")
  await t.settle()
  await page.click("#t-text")
  t.eq("typing at the end adds text after the tokens", await t.text("#t-text"), "Open [@routes.ts](file:routes.ts) and [@app.ts](file:app.ts) now")
  await page.click("#t-editor")
  await t.press("Control+End")
  await t.press("End")
  for (let i = 0; i < 4; i++) await t.press("Backspace")
  await t.press("Backspace")
  await t.settle()
  await page.click("#t-text")
  t.eq("Backspace after a token removes the whole token", (await t.text("#t-text")) + " " + (await tokens("#t-editor")), "Open [@routes.ts](file:routes.ts) and 1")
  await page.locator("#t-editor [data-slot=token-input-token-remove]").first().click()
  await t.settle()
  await page.click("#t-text")
  t.eq("a token's remove part removes it", (await t.text("#t-text")) + "|" + (await tokens("#t-editor")), "Open  and|0")

  await page.click("#c-editor")
  await t.press("Control+End")
  await t.press("End")
  await page.keyboard.type(", hello")
  await t.settle()
  t.eq("controlled: each edit reaches the app", await t.text("#c-value"), "Hi [@ada](user:ada), hello")
  await t.press("Enter")
  t.eq("Enter submits the value", await t.text("#c-sent"), "Hi [@ada](user:ada), hello")
  await t.press("Shift+Enter")
  await page.keyboard.type("x")
  await t.settle()
  t.eq("Shift+Enter adds a line", await t.text("#c-value"), "Hi [@ada](user:ada), hello\nx")
  await page.click("#c-clear")
  await t.settle()
  t.eq("controlled: a value set from outside replaces the content", (await tokens("#c-editor")) + "|" + (await page.locator("#c-editor").innerText()).trim() + "|" + (await t.attr("#c-editor", "data-empty")), "0||")
}
