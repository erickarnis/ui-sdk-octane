export default async function dialog(t) {
  const { page } = t
  const inTopLayer = (selector) => page.locator(selector).evaluate((el) => el.matches(":popover-open"))
  t.eq("trigger advertises a dialog", await t.attr("#dlg-trigger", "aria-haspopup"), "dialog")
  t.eq("closed content is not in the page", await t.count("#dlg"), 0)
  await page.locator("#dlg-trigger").focus()
  await t.press("Enter")
  t.eq("Enter opens it", await t.count("#dlg"), 1)
  t.eq("a modal dialog, named by its title and described by its description", [await t.attr("#dlg", "role"), await t.attr("#dlg", "aria-modal"), await t.attr("#dlg", "aria-labelledby"), await t.attr("#dlg", "aria-describedby")].join(" "), "dialog true dlg-title dlg-description")
  t.eq("content and backdrop are in the top layer", (await inTopLayer("#dlg")) && (await inTopLayer("#dlg-backdrop")), true)
  t.eq("opening moves focus to the first focusable element", await t.active(), "dlg-input")
  t.eq("trigger points at the content", await t.attr("#dlg-trigger", "aria-controls"), "dlg")
  await t.press("Tab")
  await t.press("Tab")
  t.eq("Tab moves through the dialog in order", await t.active(), "dlg-close")
  await t.press("Tab")
  t.eq("Tab from the last element wraps to the first", await t.active(), "dlg-input")
  await page.keyboard.press("Shift+Tab")
  t.eq("Shift+Tab from the first wraps to the last", await t.active(), "dlg-close")
  t.eq("the rest of the page is inert", await page.locator("#cdlg-outside").evaluate((el) => el.inert), true)
  await page.click("#dlg-copy")
  t.eq("pressing a button inside keeps it open", await t.count("#dlg"), 1)
  await t.press("Escape")
  t.eq("Escape closes it", await t.count("#dlg"), 0)
  t.eq("and returns focus to the trigger", await t.active(), "dlg-trigger")
  t.eq("the page is usable again", await page.locator("[inert]").count(), 0)
  await t.press("Space")
  t.eq("Space opens it", await t.count("#dlg"), 1)
  await page.click("#dlg-close")
  t.eq("the close button closes it and returns focus", (await t.count("#dlg")) + " " + (await t.active()), "0 dlg-trigger")
  await page.click("#dlg-trigger")
  await page.mouse.click(1000, 600)
  await t.settle()
  t.eq("pressing the backdrop closes it and returns focus", (await t.count("#dlg")) + " " + (await t.active()), "0 dlg-trigger")

  t.eq("the shortcut shows in the trigger, and the trigger says it", (await t.text("#cdlg-shortcut")) !== "" && (await t.attr("#cdlg-trigger", "aria-keyshortcuts")) !== null, true)
  await page.click("#cdlg-trigger")
  t.eq("controlled: press reaches the app and opens", (await t.text("#cdlg-open")) + " " + (await t.count("#cdlg")), "true 1")
  await t.press("Escape")
  t.eq("controlled: Escape reaches the app with its reason", (await t.text("#cdlg-open")) + " " + (await t.text("#cdlg-reasons")), "false trigger-press,escape-key")
  await page.click("#cdlg-outside")
  t.eq("controlled: opened from outside", await t.count("#cdlg"), 1)
  t.eq("a dialog opened from outside moves focus inside", await t.active(), "cdlg-close")
  await page.click("#cdlg-close")
  await page.keyboard.press("Control+j")
  await t.settle()
  t.eq("the trigger's shortcut opens it", await t.count("#cdlg"), 1)
  await t.press("Escape")

  await page.click("#rdlg-trigger")
  t.eq("a trigger outside the dialog opens it through the controller", await t.count("#rdlg"), 1)
  t.eq("the outside trigger points at it", await t.attr("#rdlg-trigger", "aria-controls"), "rdlg")
  await t.press("Escape")
  t.eq("and takes focus back", await t.active(), "rdlg-trigger")
  await page.click("#rdlg-api")
  t.eq("controller.open() opens it", await t.count("#rdlg"), 1)
  await page.click("#rdlg-close")

  await page.click("#outer-trigger")
  await page.click("#inner-trigger")
  t.eq("a nested dialog opens over the outer one", (await t.count("#outer")) + " " + (await t.count("#inner")), "1 1")
  await t.press("Tab")
  t.eq("Tab stays inside the nested dialog", await t.active(), "inner-close")
  await t.press("Escape")
  t.eq("Escape closes only the nested dialog and returns focus to its trigger", [await t.count("#outer"), await t.count("#inner"), await t.active()].join(" "), "1 0 inner-trigger")
  await t.press("Escape")
  t.eq("a second Escape closes the outer dialog", (await t.count("#outer")) + " " + (await t.active()), "0 outer-trigger")

  await page.click("#nm-trigger")
  t.eq("non-modal: opens without aria-modal", (await t.count("#nm")) + " " + (await t.attr("#nm", "aria-modal")), "1 null")
  await page.click("#nm-beside")
  t.eq("non-modal: the page stays usable", await t.active(), "nm-beside")

  await page.click("#pdlg-trigger")
  t.eq("with a container, the content renders into it", await page.locator("#portal-root > #pdlg").count(), 1)
  await page.click("#pdlg-close")
  t.eq("and leaves it when closed, with focus back on the trigger", (await page.locator("#portal-root > *").count()) + " " + (await t.active()), "0 pdlg-trigger")
}
