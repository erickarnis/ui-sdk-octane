export default async function triggerMenu(t) {
  const { page } = t
  const lit = (list) => page.locator(list + " [data-highlighted]").allTextContents().then((all) => all.join(","))
  const shown = (list) => page.locator(list + " [role=option]:visible").allTextContents().then((all) => all.join(","))
  t.eq("the input says it has a listbox popup, closed", [await t.attr("#tm-input", "aria-haspopup"), await t.count("#tm-content")].join(" "), "listbox 0")
  await page.click("#tm-input")
  await page.keyboard.type("hi @")
  await t.settle()
  t.eq("the trigger opens the menu with its items, focus staying in the input", [await t.visible("#tm-content"), await shown("#tm-list"), await t.active(), await t.attr("#tm-input", "data-trigger")].join(" "), "true Ada,Alan,Grace tm-input @")
  await page.keyboard.type("al")
  await t.settle()
  t.eq("typing after it filters", (await shown("#tm-list")) + " " + (await lit("#tm-list")), "Alan Alan")
  await t.press("Enter")
  await t.settle()
  t.eq("Enter inserts the item in place of the query and closes", [await page.inputValue("#tm-input"), await t.visible("#tm-content"), await t.text("#tm-picked")].join("|"), "hi @Alan |false|alan")
  await page.keyboard.type("@")
  await t.settle()
  await t.press("ArrowDown")
  await t.press("ArrowDown")
  t.eq("arrows move the highlight", await lit("#tm-list"), "Grace")
  await t.press("ArrowDown")
  t.eq("and wrap", await lit("#tm-list"), "Ada")
  await page.keyboard.type("zz")
  await t.settle()
  t.eq("no match keeps it open with the empty part", (await t.visible("#tm-content")) + " " + (await shown("#tm-list")) + "|" + (await t.text("#tm-empty")), "true |Nobody")
  await t.press("Escape")
  t.eq("Escape closes it and keeps the text", (await t.visible("#tm-content")) + " " + (await page.inputValue("#tm-input")), "false hi @Alan @zz")
  await page.fill("#tm-input", "")
  await page.keyboard.type("/")
  await t.settle()
  t.eq("another trigger shows its own items", await shown("#tm-list"), "help,clear,share")
  await page.locator("#tm-list [role=option]", { hasText: "share" }).click()
  t.eq("a click inserts an item", await page.inputValue("#tm-input"), "/share ")
  await page.keyboard.type("x /")
  await t.settle()
  t.eq("a line-boundary trigger opens only at a line's start", await t.count("#tm-content"), 0)

  await page.click("#tk-editor")
  await page.keyboard.type("ping @gr")
  await t.settle()
  const list = "#" + (await t.attr("#tk-editor", "aria-controls")).replaceAll(":", "\\:")
  t.eq("inside a token input it uses that editor", await shown(list), "Grace")
  await t.press("Enter")
  await t.settle()
  t.eq("and inserts a token", (await t.text("#tk-value")) + " " + (await t.count("#tk-editor [data-slot=token-input-host]")), "ping [@Grace](user:grace) 1")
}
